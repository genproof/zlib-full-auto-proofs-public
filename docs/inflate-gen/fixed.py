#!/usr/bin/env python3
"""Generator of src/proof/inflate/Fixed.v: inftrees.c's fixed decoding tables (inffixed.h) as lists of entries.

inflate's fixed-code tables lenfix[512] and distfix[32] are static arrays of `code` {op, bits, val}; their Clight
(src/inftrees/code.v, the globals v_lenfix and v_distfix) initialises each entry with Init_int8 op, Init_int8 bits,
Init_int16 val.  This script reads those initialisers and writes them as `mkE op bits val` entries of the inftrees
model (lenfix_list, distfix_list); the proofs tie the lists to the globals by computation.

Usage (from the repository root):  python3 docs/inflate-gen/fixed.py [--check]
  --check: only compare with src/proof/inflate/Fixed.v (exit 1 if it differs).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CODE = os.path.join(ROOT, 'src', 'inftrees', 'code.v')
OUT = os.path.join(ROOT, 'src', 'proof', 'inflate', 'Fixed.v')
HEADER = '''(* Generated by docs/inflate-gen/fixed.py from src/inftrees/code.v (inffixed.h): the fixed decoding tables
   lenfix[512] and distfix[32] as entries of the inftrees model.  Do not edit: run the generator. *)
From Coq Require Import ZArith List.
Require Export Zlib.proof.inftrees.model.
Import ListNotations.
Local Open Scope Z_scope.
'''


def table(code, name, n):
    m = re.search(r'^Definition v_%s := \{\|\n  gvar_info := \(tarray \(Tstruct ___gp_code noattr\) %d\);\n'
                  r'  gvar_init := \((.*?)\);\n' % (name, n), code, re.M | re.S)
    if not m:
        sys.exit('fixed.py: no v_%s of %d entries in src/inftrees/code.v' % (name, n))
    inits = re.findall(r'Init_int(8|16) \(Int\.repr (-?\d+)\)', m.group(1))
    if len(inits) != 3 * n or any(inits[3 * i + k][0] != w for i in range(n) for k, w in enumerate(('8', '8', '16'))):
        sys.exit('fixed.py: v_%s is not %d entries of Init_int8, Init_int8, Init_int16' % (name, n))
    return [tuple(int(inits[3 * i + k][1]) for k in range(3)) for i in range(n)]


def generate():
    code = open(CODE).read()
    out = [HEADER]
    for name, n in (('lenfix', 512), ('distfix', 32)):
        es = table(code, name, n)
        out.append('\nDefinition %s_list : list entry := [\n' % name)
        out.append(';\n'.join('  mkE %d %d %d' % e for e in es) + ' ].\n')
    return ''.join(out) + '\n'


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('src/proof/inflate/Fixed.v: %s' % ('identical' if same else 'differs'))
        sys.exit(0 if same else 1)
    open(OUT, 'w').write(text)
    print('wrote src/proof/inflate/Fixed.v')


if __name__ == '__main__':
    main()
