#!/usr/bin/env python3
"""Generator of src/proof/inflate/Records.v: the records of the inflate model, with one setter per field.

The model of inflate (src/proof/inflate/) keeps the inflate_state as a record istate, the application's gz_header
as a record hstate and the machine of one inflate() call as a record mst.  Coq has no record update, so every
field f of a record gets a setter set_f r v: the record r with v in f (the constructor applied to the other
fields' projections).  This script writes the three records and their setters from the field lists below.

Usage (from the repository root):  python3 docs/inflate-gen/records.py [--check]
  --check: only compare with src/proof/inflate/Records.v (exit 1 if it differs).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'src', 'proof', 'inflate', 'Records.v')


def rec(name, ctor, fields):
    out = []
    out.append(f"Record {name} := {ctor} {{")
    out.append(";\n".join(f"  {f} : {t}" for f, t in fields) + " }.")
    out.append("")
    for i, (f, t) in enumerate(fields):
        args = " ".join(("v" if j == i else f"({g} r)") for j, (g, _) in enumerate(fields))
        out.append(f"Definition set_{f} (r: {name}) (v: {t}) : {name} := {ctor} {args}.")
    out.append("")
    return "\n".join(out)


# the inflate_state of inflate.h
istate = [("i_mode", "Z"), ("i_last", "Z"), ("i_wrap", "Z"), ("i_havedict", "Z"), ("i_flags", "Z"), ("i_dmax", "Z"),
          ("i_check", "Z"), ("i_total", "Z"), ("i_head", "bool"), ("i_wbits", "Z"), ("i_wsize", "Z"),
          ("i_whave", "Z"), ("i_wnext", "Z"), ("i_win", "bool"), ("i_wdata", "list Z"), ("i_hold", "Z"),
          ("i_bits", "Z"), ("i_length", "Z"), ("i_offset", "Z"), ("i_extra", "Z"), ("i_lencode", "tref"),
          ("i_distcode", "tref"), ("i_lenbits", "Z"), ("i_distbits", "Z"), ("i_ncode", "Z"), ("i_nlen", "Z"),
          ("i_ndist", "Z"), ("i_have", "Z"), ("i_next", "Z"), ("i_lens", "list Z"), ("i_codes", "list entry"),
          ("i_sane", "Z"), ("i_back", "Z"), ("i_was", "Z")]
# the application's gz_header (zlib.h)
hstate = [("h_text", "Z"), ("h_time", "Z"), ("h_xflags", "Z"), ("h_os", "Z"), ("h_xp", "bool"), ("h_extra_len", "Z"),
          ("h_extra_max", "Z"), ("h_xbuf", "list Z"), ("h_np", "bool"), ("h_name_max", "Z"), ("h_nbuf", "list Z"),
          ("h_cp", "bool"), ("h_comm_max", "Z"), ("h_cbuf", "list Z"), ("h_hcrc", "Z"), ("h_done", "Z")]
# the machine of one inflate() call: the state, the header, the stream's input and output, inflate()'s locals
mst = [("m_s", "istate"), ("m_h", "hstate"), ("m_inp", "list Z"), ("m_aout", "Z"), ("m_nx", "Z"), ("m_ow", "list Z"),
       ("m_hold", "Z"), ("m_bits", "Z"), ("m_in", "Z"), ("m_out", "Z"), ("m_ret", "Z"), ("m_leave", "Z"),
       ("m_adler", "Z"), ("m_msg", "option msgid"), ("m_tin", "Z"), ("m_tout", "Z"), ("m_snx", "Z"), ("m_sow", "Z")]

HEADER = """(* Generated by docs/inflate-gen/records.py: the records of the inflate model and one setter per field.
   Do not edit: change the generator and run it. *)
From Coq Require Import ZArith List Lia Bool.
Require Import VST.zlist.sublist.
Require Import compcert.common.AST.
Require Export Zlib.proof.inftrees.model.
Import ListNotations.
Local Open Scope Z_scope.

(* Where a table pointer points: inftrees.c's static fixed tables, or offset k into state->codes. *)
Inductive tref := TLenfix | TDistfix | TCodes (k: Z).

(* strm->msg: NULL or one of the string literals of inflate.c (M_...) or inffast.c (F_...) *)
Inductive msgid :=
  | M_hdr_check | M_method | M_wsize | M_hflags | M_hcrc | M_btype | M_stored | M_toomany
  | M_cl_set | M_repeat | M_eob | M_ll_set | M_d_set | M_ll_code | M_d_code | M_far | M_dcheck
  | M_lcheck
  | F_far | F_d_code | F_ll_code.

"""


def generate():
    return HEADER + rec("istate", "IS", istate) + "\n" + rec("hstate", "HS", hstate) + "\n" + rec("mst", "MS", mst)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('src/proof/inflate/Records.v: %s' % ('identical' if same else 'differs'))
        sys.exit(0 if same else 1)
    open(OUT, 'w').write(text)
    print('wrote src/proof/inflate/Records.v')


if __name__ == '__main__':
    main()
