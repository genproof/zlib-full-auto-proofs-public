#!/usr/bin/env python3
"""Generator of src/contracts/laws.v: every law of `suite` as a theorem of its own.

quickproof/tools/new_contract.py states each law in its own contract file, `Theorem <law> : harness_safe
whole_prog.`, on that file's whole_prog.  The proof cannot prove it there: suite.v Requires every contract file for
its whole_prog, so a contract file that Required the proof would close a cycle.  So each contract file keeps only its
program (the module Harness, the link_* definitions, whole_prog and whole_prog_undefined), and laws.v states the law
with the same name and the same statement on that program,

    Theorem <law> : harness_safe Zlib.contracts.<law>.whole_prog.

proved as a projection of a proved conjunction of src/contracts/suite.v:
- the 17 x_ laws from `suite_x` (the conjunction of the x_ laws, proved from the parts of src/proof/);
- the other laws from `suite` itself.
A law that another file of src/contracts/ already states (x_crc32_ref, in laws_checksums.v) is left out.  The
laws that the contract leaves out of `suite` (false on this code) get no theorem.

The conjunctions are read from suite.v (their conjuncts in order, `harness_safe Zlib.contracts.<law>.whole_prog`);
the i-th conjunct of n is proj1 (proj2^i C) for i < n - 1 and proj2^(n-1) C for the last one.

Usage (from the repository root):  python3 docs/laws-gen/laws.py [--check]
  --check: only compare with src/contracts/laws.v (exit 1 if it differs).
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CONTRACTS = os.path.join(ROOT, 'src', 'contracts')
OUT = os.path.join(CONTRACTS, 'laws.v')
LAW = re.compile(r'harness_safe\s+Zlib\.contracts\.(\w+)\.whole_prog')
# the tag of the contract commit whose contract files state the laws
CONTRACT_TAG = 'contract'


def blank_comments(text):
    out, depth, i = [], 0, 0
    while i < len(text):
        two = text[i:i + 2]
        if two == '(*':
            depth += 1; out.append('  '); i += 2
        elif two == '*)' and depth:
            depth -= 1; out.append('  '); i += 2
        else:
            out.append(text[i] if not depth or text[i] == '\n' else ' '); i += 1
    return ''.join(out)


def conjuncts(code, head):
    """The laws of the conjunction `<head> : C1 /\\ ... /\\ Cn.` of suite.v, in order."""
    m = re.search(r'^%s\s*:(.*?)\.\s*$' % re.escape(head), code, re.M | re.S)
    if not m:
        sys.exit('laws.py: no "%s" in src/contracts/suite.v' % head)
    parts = [p.strip() for p in m.group(1).split('/\\')]
    laws = [LAW.fullmatch(p) for p in parts]
    if not all(laws):
        sys.exit('laws.py: "%s" is not a conjunction of harness_safe Zlib.contracts.<law>.whole_prog' % head)
    return [x.group(1) for x in laws]


def projection(i, n, c):
    if i < n - 1:
        return 'proj1 %s' % nest(i, c) if i else 'proj1 %s' % c
    return nest(n - 1, c)[1:-1]


def nest(k, c):
    """(proj2 (proj2 ... c)) with k proj2, parenthesized."""
    t = c
    for _ in range(k):
        t = '(proj2 %s)' % t
    return t


def stated_elsewhere():
    out = set()
    for f in glob.glob(os.path.join(CONTRACTS, '*.v')):
        if os.path.basename(f) in ('laws.v', 'suite.v'):
            continue
        code = blank_comments(open(f).read())
        out |= set(re.findall(r'^Theorem (\w+)\s*:\s*harness_safe\s+Zlib\.contracts\.\w+\.whole_prog\s*\.', code, re.M))
    return out


def left_out(code):
    """The sentence on the laws that the contract leaves out of `suite` (false on this code), if there are any."""
    suite = set(conjuncts(code, 'Theorem suite'))
    laws = sorted(os.path.basename(h)[:-2] for h in glob.glob(os.path.join(ROOT, 'harness', '*.c')))
    out = [law for law in laws if law not in suite]
    if not out:
        return ''
    return ('\n   The laws that the contract leaves out of `suite` (false on this code:\n   %s) have no theorem.'
            % ', '.join(out))


def generate():
    code = blank_comments(open(os.path.join(CONTRACTS, 'suite.v')).read())
    suite = conjuncts(code, 'Theorem suite')
    sx = conjuncts(code, 'Lemma suite_x')
    if not set(sx) <= set(suite):
        sys.exit('laws.py: suite_x has a law that suite does not have')
    skip = stated_elsewhere()
    xs = [(law, projection(i, len(sx), 'Zlib.contracts.suite.suite_x')) for i, law in enumerate(sx) if law not in skip]
    short = [(law, projection(i, len(suite), 'Zlib.contracts.suite.suite')) for i, law in enumerate(suite)
             if law not in sx and law not in skip]
    out = ['''(* Generated by docs/laws-gen/laws.py from src/contracts/suite.v.  Do not edit: run the generator.
   ======================================================================
   The laws of the project, one theorem each, with the names and the
   statements that quickproof/tools/new_contract.py generated in
   src/contracts/<law>.v (`Theorem <law> : harness_safe whole_prog`, there
   with that file's whole_prog; see the commit tagged `%s`).  They
   are stated here because the proof Requires those files for whole_prog:
   proving them in place would be a cycle.  Each is a projection of a
   proved conjunction of suite.v: the x_ laws of `suite_x`, which proves
   all 17 on one shared specification of the code under test, and the
   short laws of `suite`.

   %s is not here: it is stated and proved (Qed) in another file of
   src/contracts/ (laws_checksums.v), and suite.v uses that theorem.%s
   ====================================================================== *)
''' % (CONTRACT_TAG, ', '.join(sorted(skip)), left_out(code)), 'Require Import QuickProof.Contract.']
    out += ['Require Zlib.contracts.%s.' % law for law in sorted(l for l, _ in xs + short)]
    out += ['Require Zlib.contracts.suite.', '', '(* The 17 x_ laws (but %s): projections of `suite_x`. *)' % ', '.join(sorted(skip)), '']
    for law, term in xs:
        out += ['Theorem %s : harness_safe Zlib.contracts.%s.whole_prog.' % (law, law),
                'Proof. exact (%s). Qed.' % term, '']
    out += ['(* The %d short laws: projections of `suite`. *)' % len(short), '']
    for law, term in short:
        out += ['Theorem %s : harness_safe Zlib.contracts.%s.whole_prog.' % (law, law),
                'Proof. exact (%s). Qed.' % term, '']
    return '\n'.join(out).rstrip('\n') + '\n'


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('src/contracts/laws.v: %s' % ('identical' if same else 'differs'))
        sys.exit(0 if same else 1)
    open(OUT, 'w').write(text)
    print('wrote src/contracts/laws.v')


if __name__ == '__main__':
    main()
