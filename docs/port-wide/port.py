#!/usr/bin/env python3
"""Generator of the deflate core theory for calls of up to 2^32 - 1 bytes of input (src/proof/wide/).

The core part of the deflate laws' model theory (src/proof/deflate/LTC*.v, LTCore.v) runs the compression
functions on streams offering at most 2^30 bytes of input (LTCSpecs.zin_in) and of output space
(LTDefs.zin_ok); every loop invariant of the compressors carries these bounds.  The laws res_free_deflate /
res_memory_deflate make one deflate() call of up to 2^32 - 1 bytes in and out.  The arithmetic of the proofs
never needs the bounds to be that small, so the same proofs hold with the bounds 2^32 - 1, except where
the C really computes in 32 bits with the input size (deflate_stored's `left + strm->avail_in`).

This script reuses docs/port-za/port.py (the declaration-by-declaration port: a declaration changed by a
substitution or a patch, or mentioning a changed name, is copied with the suffix _w; the others are used from
the original module, which the ported one `Require Export`s), with:
- the configuration docs/port-wide/cfg_<side>.py (TARGETS, PREFIXES, SUBST, PATCHES as for port-za);
- the ported module Zlib.proof.X written to src/proof/wide/X.v (module Zlib.proof.wide.X), no section.

Usage (from the repository root):  python3 docs/port-wide/port.py <side> [--check] [--list]
"""
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('portza', os.path.join(HERE, '..', 'port-za', 'port.py'))
P = importlib.util.module_from_spec(spec)
spec.loader.exec_module(P)

ROOT = P.ROOT
P.SUFFIX = '_w'


def new_name(m):
    assert m.startswith('Zlib.proof.'), m
    return 'Zlib.proof.wide.' + m[len('Zlib.proof.'):]


P.new_name = new_name


def all_modules():
    mods = {}
    for f in P.glob.glob(os.path.join(ROOT, 'src', '**', '*.v'), recursive=True):
        rel = os.path.relpath(f, os.path.join(ROOT, 'src'))
        if rel.startswith(os.path.join('proof', 'za') + os.sep) or rel.startswith(os.path.join('proof', 'wide') + os.sep):
            continue
        mods['Zlib.' + rel[:-2].replace(os.sep, '.')] = f
    return mods


def load_cfg(side):
    path = os.path.join(HERE, 'cfg_%s.py' % side)
    sp = importlib.util.spec_from_file_location('cfg_' + side, path)
    mod = importlib.util.module_from_spec(sp)
    sp.loader.exec_module(mod)
    return mod


def main():
    side = sys.argv[1]
    check = '--check' in sys.argv
    cfg = load_cfg(side)
    mods = all_modules()
    order, deps = P.topo(cfg, mods)
    candidates = [m for m in order if m.startswith(tuple(cfg.PREFIXES))]
    tainted, per_mod, used = set(), {}, set()
    for m in candidates:
        us = P.units(open(mods[m]).read())
        for u in us:
            orig = t = u.text
            for pat, rep in cfg.SUBST:
                t = re.sub(pat, rep, t)
            for k, (pm, old, new) in enumerate(cfg.PATCHES):
                if pm == m and old in t:
                    if t.count(old) != 1:
                        sys.exit('patch %d of %s applies %d times' % (k, m, t.count(old)))
                    t = t.replace(old, new); used.add(k)
            u.text = t
            u.changed = t != orig
        per_mod[m] = us
    # a declaration is tainted when it is changed or mentions a tainted name visible at its place: the
    # module's own earlier declaration of that name if there is one, else one of its (transitive) imports.
    # The names are scoped so: two modules may define the same name (e.g. the loop invariants [linv] of
    # LTCStoredLoop and LTCLiveKit), and only the tainted one is renamed.
    closure = {}

    def clos(m):
        if m not in closure:
            closure[m] = set()
            for d in deps.get(m, []):
                closure[m] |= {d} | clos(d)
        return closure[m]
    tainted_in = {}
    for m in candidates:
        vis = set()
        for d in clos(m):
            vis |= tainted_in.get(d, set())
        tainted_in[m] = set()
        for u in per_mod[m]:
            if u.kind == 'cmd':
                u.tainted = u.changed
            elif u.changed or P.mentions(u.text, vis):
                u.tainted = True
                tainted_in[m].update(u.names); vis |= set(u.names); tainted.update(u.names)
            else:
                vis -= set(u.names)
            u.vis = set(vis)
    ported = [m for m in candidates if any(u.tainted for u in per_mod[m])]
    changed = True
    while changed:
        changed = False
        for m in candidates:
            if m not in ported and any(d in ported for d in deps[m]):
                ported.append(m); changed = True
    ported_set = set(ported)
    bad = 0
    for m in candidates:
        if m not in ported_set:
            continue
        out = ['(* Generated by docs/port-wide/port.py from %s: its declarations that depend on the\n'
               '   size bounds of the input / output of a call, for calls of up to 2^32 - 1 bytes, with the suffix _w;\n'
               '   the others are the original ones (Require Export).  Do not edit: change the configuration\n'
               '   docs/port-wide/cfg_%s.py and run the generator. *)\n' % (os.path.relpath(mods[m], ROOT), side)]
        exported = False
        for u in per_mod[m]:
            txt = P.rename(u.text, u.vis, ported_set)
            body = P.strip_comments_strings(u.text)
            if u.kind == 'cmd':
                if not exported and not re.search(r'\bRequire\b', body) and body.strip():
                    out.append('\nRequire Export %s.\n' % m); exported = True
                out.append(txt); continue
            if not exported:
                out.append('\nRequire Export %s.\n' % m); exported = True
            if u.kind == 'local' or u.tainted:
                out.append(txt)
        if not exported:
            out.append('\nRequire Export %s.\n' % m)
        txt = ''.join(out)
        if not txt.endswith('\n'):
            txt += '\n'
        dst = os.path.join(ROOT, 'src', *new_name(m).split('.')[1:]) + '.v'
        if check:
            if not os.path.exists(dst) or open(dst).read() != txt:
                print('differs:', dst); bad += 1
            continue
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, 'w') as f:
            f.write(txt)
    print('%d modules %s, %d tainted names' % (len(ported), 'checked' if check else 'written', len(tainted)))
    if '--list' in sys.argv:
        for m in order:
            if m in ported_set:
                print(m, [n for u in per_mod[m] if u.tainted for n in u.names])
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
