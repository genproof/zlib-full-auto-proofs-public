#!/usr/bin/env python3
"""The generator of src/proof/wide/roundtrip/RTIG*.v, the wide port of the round trip's generalized decode theory:
docs/port-za/port.py with the configuration docs/port-za/cfg_wide_rtig.py.

That configuration extends cfg_wide_decode.py (the RTIG modules require rfc1951/Decode.v), so port.py ports the
modules of src/proof/wide/rfc1951/ and src/proof/wide/inflate/ again; their names tainted by the RTIG modules
(copies of rfc1951's, with the same names) would change their texts.  This wrapper therefore
- checks that src/proof/wide/rfc1951/ and src/proof/wide/inflate/ are the port of cfg_wide_decode.py
  (`port.py wide_decode --check`; it never writes them), and
- writes only the modules Zlib.proof.wide.roundtrip.RTIG* of the port of cfg_wide_rtig.py, with their own header.
The RTIG modules are ported after all those of cfg_wide_decode.py, so the declarations of the latter are tainted
exactly as in their own port, and a RTIG copy is tainted when its original in rfc1951 is.

Usage (from the repository root):  python3 docs/port-za/port_rtig.py [--check] [--list]"""
import builtins
import importlib.util
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name, file):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, file))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


port = load('port', 'port.py')
cfg = load('cfg_wide_rtig', 'cfg_wide_rtig.py')

OWN = os.path.join(port.ROOT, 'src', 'proof', cfg.OUT, 'roundtrip', 'RTIG')

# the header port.py writes for cfg_wide_decode.py, and the one of the RTIG modules
PAIRS = [('Generated by docs/port-za/port.py from', 'Generated by docs/port-za/port_rtig.py from'),
         (cfg.WHAT, cfg.WHAT_RTIG),
         ('docs/port-za/cfg_wide_decode.py and run the generator.',
          'docs/port-za/cfg_wide_rtig.py and run docs/port-za/port_rtig.py.')]


def run(argv, opener=None):
    """port.main with these arguments (and port's `open` replaced by opener); its exit code."""
    port.open = opener or builtins.open
    sys.argv = [sys.argv[0]] + argv
    try:
        port.main()
        return 0
    except SystemExit as e:
        if e.code and not isinstance(e.code, int):
            print(e.code)
            return 1
        return e.code or 0
    finally:
        port.open = builtins.open


def main():
    args = sys.argv[1:]
    check = '--check' in args
    # the modules of cfg_wide_decode.py on disk
    code = run(['wide_decode', '--check'])
    if code:
        sys.exit('src/proof/wide/ is not the port of cfg_wide_decode.py: run docs/port-za/port.py wide_decode first')
    # the port of cfg_wide_rtig.py, in memory
    out = {}

    def opener(path, mode='r', *a, **k):
        p = os.path.abspath(path)
        if 'w' in mode:
            buf = io.StringIO()
            buf.close = lambda: out.__setitem__(p, buf.getvalue())
            return buf
        if p.startswith(os.path.join(port.ROOT, 'src', 'proof', cfg.OUT) + os.sep):
            return io.StringIO('')  # every ported module is produced
        return builtins.open(path, mode, *a, **k)
    port.load_cfg = lambda side: cfg
    out_std = sys.stdout
    if '--list' not in args:
        sys.stdout = io.StringIO()  # its count of modules is about the port in memory
    try:
        code = run(['wide_decode'] + [a for a in args if a == '--list'], opener)
    finally:
        sys.stdout = out_std
    if code:
        sys.exit(code)
    bad = 0
    own = sorted(p for p in out if p.startswith(OWN))
    for p in own:
        txt = out[p]
        for a, b in PAIRS:
            assert txt.count(a) >= 1, (p, a)
            txt = txt.replace(a, b, 1)
        if os.path.exists(p) and builtins.open(p).read() == txt:
            continue
        if check:
            print('differs:', os.path.relpath(p, port.ROOT)); bad += 1
            continue
        with builtins.open(p, 'w') as f:
            f.write(txt)
    print('%d RTIG modules %s' % (len(own), 'checked' if check else 'written'))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
