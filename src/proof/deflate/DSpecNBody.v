(* deflate() with next_in = Z_NULL allowed: the bodies of DSpecN.deflate_bodyN_stmt (deflate against
   deflate_specN, its input-carrying callees against their generalized specifications).

   The proofs are those of src/proof/deflate/ ported to DSpecN.in_ptrN / DSpecN.in_objN (src/proof/dnull/deflate/,
   generated by docs/port-za/port_dnull.py); GN is the list of the ported specifications
   of in_funs, and the ported contexts are DSpec's with GN substituted. *)
Require Import VST.floyd.proofauto.
Require Import Zlib.proof.deflate.DSpecN.
Require Import Zlib.proof.dnull.deflate.DSpec_N.
Require Import Zlib.proof.dnull.deflate.Obligations_N.
Require Import Zlib.proof.dnull.deflate.Body_read_buf_N.
Require Import Zlib.proof.dnull.deflate.Body_flush_pending_N.
Require Import Zlib.proof.dnull.PartFillWindow.
Require Import Zlib.proof.dnull.PartStored.
Require Import Zlib.proof.dnull.PartFast.
Require Import Zlib.proof.dnull.PartSlow.
Require Import Zlib.proof.dnull.PartRle.
Require Import Zlib.proof.dnull.PartHuff.
Require Import Zlib.proof.dnull.PartDeflate.
Require Import Zlib.deflate.code.

(* the ported specifications of the input-carrying functions, in the order of in_funs *)
Definition GN : funspecs :=
  [read_buf_spec_N; flush_pending_spec_N; fill_window_spec_N; deflate_stored_spec_N; deflate_fast_spec_N;
   deflate_slow_spec_N; deflate_rle_spec_N; deflate_huff_spec_N].

(* the ported deflate specification is deflate_specN *)
Lemma deflate_spec_N_eq : deflate_spec_N = deflate_specN.
Proof. reflexivity. Qed.

Lemma gn_read_buf : gn_spec GN _read_buf (snd read_buf_spec) = read_buf_spec_N.
Proof. reflexivity. Qed.
Lemma gn_flush_pending : gn_spec GN _flush_pending (snd flush_pending_spec) = flush_pending_spec_N.
Proof. reflexivity. Qed.
Lemma gn_fill_window : gn_spec GN _fill_window (snd fill_window_spec) = fill_window_spec_N.
Proof. reflexivity. Qed.
Lemma gn_deflate_stored : gn_spec GN _deflate_stored (snd deflate_stored_spec) = deflate_stored_spec_N.
Proof. reflexivity. Qed.
Lemma gn_deflate_fast : gn_spec GN _deflate_fast (snd deflate_fast_spec) = deflate_fast_spec_N.
Proof. reflexivity. Qed.
Lemma gn_deflate_slow : gn_spec GN _deflate_slow (snd deflate_slow_spec) = deflate_slow_spec_N.
Proof. reflexivity. Qed.
Lemma gn_deflate_rle : gn_spec GN _deflate_rle (snd deflate_rle_spec) = deflate_rle_spec_N.
Proof. reflexivity. Qed.
Lemma gn_deflate_huff : gn_spec GN _deflate_huff (snd deflate_huff_spec) = deflate_huff_spec_N.
Proof. reflexivity. Qed.

Lemma gn_ctx_read_buf : subst_specs GN Gprog_read_buf = Gprog_read_buf.
Proof. reflexivity. Qed.
Lemma gn_ctx_flush_pending : subst_specs GN Gprog_flush_pending = Gprog_flush_pending.
Proof. reflexivity. Qed.
Lemma gn_ctx_fill_window : subst_specs GN Gprog_fill_window = Gprog_fill_window_N.
Proof. reflexivity. Qed.
Lemma gn_ctx_compress : subst_specs GN Gprog_compress = Gprog_compress_N.
Proof. reflexivity. Qed.
Lemma gn_ctx_deflate : subst_specs GN Gprog_deflate = Gprog_deflate_N.
Proof. reflexivity. Qed.

Theorem deflate_bodyN : deflate_bodyN_stmt.
Proof.
  exists GN. split; [reflexivity |]. split.
  { repeat constructor. }
  rewrite gn_read_buf, gn_flush_pending, gn_fill_window, gn_deflate_stored, gn_deflate_fast, gn_deflate_slow,
    gn_deflate_rle, gn_deflate_huff, gn_ctx_read_buf, gn_ctx_flush_pending, gn_ctx_fill_window, gn_ctx_compress,
    gn_ctx_deflate, <- deflate_spec_N_eq.
  split; [intros; exact body_read_buf_N |].
  split; [intros; exact body_flush_pending_N |].
  split; [intros; exact dn_fill_window |].
  split; [intros; exact dn_deflate_stored |].
  split; [intros; exact dn_deflate_fast |].
  split; [intros; exact dn_deflate_slow |].
  split; [intros; exact dn_deflate_rle |].
  split; [intros; exact dn_deflate_huff |].
  intros; exact dn_deflate.
Qed.
