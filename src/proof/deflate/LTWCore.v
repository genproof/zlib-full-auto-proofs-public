    [core_theory_w]: the compressors and everything that touches the window, the hash chains and the trees state
    (LTWIface.core_facts_w), for calls offered any uInt of input and of output space and any total_in /
    total_out.  The facts are those of LTCore.core_theory with the limits of LTDefs.zin_ok removed.

    The invariant is LTCore's [W3].  The facts that do not involve the stream of a call (init, tune, frame,
    full flush, params) are LTCore's.  The compression calls ([cw_compress], [cw_still], [cw_stored_live]) use
    the ports of the LTC* proofs to the streams [zin_okw] (src/proof/wide/deflate/, generated by
    docs/port-wide/port.py with docs/port-wide/cfg_deflate.py: the bounds 2^30 of avail_in / avail_out raised to
    2^32 - 1, total_out + avail_out below 2^64; deflate_stored's comparisons of a block length with
    [left + strm->avail_in] are in 64 bits since fix F9, so no call needs more); deflateSetDictionary is
    LTWDict.W3_dict_w.
    The lemmas [core_compress3_w], [W3_still_w], [core_live3_w] below are [cw_compress], [cw_still],
    [cw_stored_live] for [W3] under their names, and [core_facts_w3] the whole record for [W3], for the users of
    the concrete invariant. *)
