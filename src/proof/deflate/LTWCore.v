(** deflate_stored is the compression function of level 0 only. *)
Lemma fn_of_stored s : prm s -> fn_of s = 0 -> d_level s = 0.
Proof.
  intros Hp E.
  assert (Hl : 0 <= d_level s <= 9)
    by (destruct Hp as (_ & _ & _ & _ & _ & _ & _ & _ & _ & _ & _ & _ & X & _); exact X).
  revert E. unfold fn_of.
  destruct (Z.eqb_spec (d_level s) 0) as [L|L]; [auto|].
  destruct (d_strategy s =? Z_HUFFMAN_ONLY); [discriminate|].
  destruct (d_strategy s =? Z_RLE); [discriminate|].
  destruct (cfg_f_cases (d_level s) ltac:(lia)) as [[C _]|[C _]]; rewrite C; discriminate.
Qed.

(** [cw_compress] for [W3]: LTCore.core_compress3 with the wide compressors. *)
Lemma core_compress3_w : fill_spec_w -> ins_spec -> lm_spec -> tally_spec2 -> fbo_spec_w -> fpend_spec2_w ->
  forall s z flush,
    W3 s -> outok s -> quiet s -> 0 <= flush <= 5 -> zin_okw z ->
    0 <= d_wrap s <= 2 -> adler_pre (d_wrap s) (z_adler z) ->
    exists s' z' bs evs, c_compress_func s z flush = Some (s', z', bs) /\ cpost W3 s z flush s' z' bs evs.
Proof.
  intros Hfill Hins Hlm Htal Hfbo Hfp s z flush [HW2 Hx] Ho Hq Hf Hz Hw Ha.
  pose proof (proj1 HW2) as HW.
  assert (Hpre : compress_pre_w s z flush)
    by exact (conj HW (conj Ho (conj Hq (conj Hf (conj Hz (conj Hw (adler_pre_ok _ _ Ha))))))).
  assert (Hpre2 : compress_pre2_w s z flush)
    by exact (conj HW2 (conj Ho (conj Hq (conj Hf (conj Hz (conj Hw (adler_pre_ok _ _ Ha))))))).
  assert (Lift : forall s' z' bs evs, fn_of s <> 2 -> fn_of s <> 3 ->
            cpost W s z flush s' z' bs evs -> cpost W3 s z flush s' z' bs evs).
  { intros s' z' bs evs N2 N3. apply cpost_imp. intros HW' Hsp. rewrite <- (fn_of_prm s s' Hsp) in N2, N3.
    split; [split; [exact HW'|exact (slow_extra_fn s' HW' N2)]|exact (huff_extra_fn s' N3)]. }
  rewrite (compress_dispatch s z flush (W_prm s HW)).
  destruct (fn_range s (W_prm s HW)) as [E|[E|[E|[E|E]]]]; rewrite E; cbn [Z.eqb Pos.eqb].
  - destruct (stored_ok2_w Hfp s z flush Hpre E) as (s' & z' & bs & evs & Ec & Hc).
    exists s', z', bs, evs. split; [exact Ec|]. apply Lift; [rewrite E; discriminate|rewrite E; discriminate|exact Hc].
  - destruct (fast_ok2_w Hfill Hins Hlm Htal Hfbo Hfp s z flush Hpre E) as (s' & z' & bs & evs & Ec & Hc).
    exists s', z', bs, evs. split; [exact Ec|]. apply Lift; [rewrite E; discriminate|rewrite E; discriminate|exact Hc].
  - destruct (slow_ok2_w Hfill Hins Hlm Htal Hfbo Hfp s z flush Hpre2 E) as (s' & z' & bs & evs & Ec & Hc).
    exists s', z', bs, evs. split; [exact Ec|]. revert Hc. apply cpost_imp. intros HW' Hsp.
    split; [exact HW'|]. apply huff_extra_fn. rewrite (fn_of_prm s s' Hsp), E. discriminate.
  - destruct (huff_okX_w Hfill Htal Hfbo s z flush Hpre Hx E) as (s' & z' & bs & evs & Ec & Hc & Hx').
    exists s', z', bs, evs. split; [exact Ec|]. revert Hc. apply cpost_imp. intros HW' Hsp.
    split; [|exact Hx']. split; [exact HW'|]. apply (slow_extra_fn s' HW'). rewrite (fn_of_prm s s' Hsp), E. discriminate.
  - destruct (rle_ok2_w Hfill Htal Hfbo Hfp s z flush Hpre E) as (s' & z' & bs & evs & Ec & Hc).
    exists s', z', bs, evs. split; [exact Ec|]. apply Lift; [rewrite E; discriminate|rewrite E; discriminate|exact Hc].
Qed.

(** [cw_still] for [W3]: LTCore.W3_still with the wide compressors. *)
Lemma W3_still_w : fill_spec_w -> ins_spec -> lm_spec -> tally_spec2 -> fbo_spec_w -> fpend_spec2_w ->
  forall s z flush s' z' bs,
    W3 s -> outok s -> quiet s -> 0 <= flush <= 5 -> zin_okw z ->
    0 <= d_wrap s <= 2 -> adler_pre (d_wrap s) (z_adler z) ->
    c_compress_func s z flush = Some (s', z', bs) ->
    ub s = 0 -> d_strstart s = 0 -> z_next_in z' = z_next_in z -> d_strstart s' = 0.
Proof.
  intros Hfill Hins Hlm Htal Hfbo Hfp s z flush s' z' bs [HW2 Hx] Ho Hq Hf Hz Hw Ha E Hub Hss Hn.
  pose proof (proj1 HW2) as HW.
  assert (Hpre : compress_pre_w s z flush)
    by exact (conj HW (conj Ho (conj Hq (conj Hf (conj Hz (conj Hw (adler_pre_ok _ _ Ha))))))).
  assert (Hpre2 : compress_pre2_w s z flush)
    by exact (conj HW2 (conj Ho (conj Hq (conj Hf (conj Hz (conj Hw (adler_pre_ok _ _ Ha))))))).
  assert (Hat : still_at s).
  { destruct (W3_pos s (conj HW2 Hx)) as (P1 & P2 & P3 & P4). unfold ub in Hub. unfold still_at. lia. }
  revert E. rewrite (compress_dispatch s z flush (W_prm s HW)).
  destruct (fn_range s (W_prm s HW)) as [F|[F|[F|[F|F]]]]; rewrite F; cbn [Z.eqb Pos.eqb]; intros E.
  - exact (still_stored_ok_w Hfill Hfp (stored_ok2_w Hfp) s z flush Hpre Hat F s' z' bs E Hn).
  - exact (still_fast_ok_w fill_idem_ok_w Hfill Hins Hlm Htal Hfbo Hfp (fast_ok2_w Hfill Hins Hlm Htal Hfbo Hfp)
             s z flush Hpre Hat F s' z' bs E Hn).
  - exact (still_slow_ok_w fill_idem_ok_w Hfill Hins Hlm Htal Hfbo Hfp (slow_ok2_w Hfill Hins Hlm Htal Hfbo Hfp)
             s z flush Hpre2 Hat F s' z' bs E Hn).
  - exact (still_huff_ok_w fill_idem_ok_w Hfill Htal Hfbo Hfp (huff_okX_w Hfill Htal Hfbo)
             s z flush Hpre Hx Hat F s' z' bs E Hn).
  - exact (still_rle_ok_w fill_idem_ok_w Hfill Htal Hfbo Hfp (rle_ok2_w Hfill Htal Hfbo Hfp)
             s z flush Hpre Hat F s' z' bs E Hn).
Qed.

(** [cw_stored_live] for [W3]: LTCore.core_live3 with the wide stored loop. *)
Lemma core_live3_w : fpend_spec2_w ->
  forall s z s' z' bs,
    W3 s -> outok s -> quiet s -> zin_okw z -> 0 <= d_wrap s <= 2 -> adler_pre (d_wrap s) (z_adler z) ->
    d_level s = 0 ->
    stored_hdr s + 5 * ((ub s + z_avail_in z) / MAX_STORED) + ub s + z_avail_in z <= z_avail_out z ->
    c_compress_func s z Z_FINISH = Some (s', z', bs) -> bs = finish_done.
Proof.
  intros Hfp s z s' z' bs [[HW _] _] Ho Hq Hz Hw Ha Hl Hroom Hc.
  assert (E : fn_of s = 0) by (unfold fn_of; rewrite Hl; reflexivity).
  rewrite (dispatch_stored s z Z_FINISH (W_prm s HW) E) in Hc.
  exact (live_ok2_w Hfp s z s' z' bs HW Ho Hq Hz Hw (adler_pre_ok _ _ Ha) Hl Hroom Hc).
Qed.

(** [core_facts_w] for LTCore's invariant [W3]. *)
Lemma core_facts_w3 : Zlib.proof.huffman.Overlay.overlay_statement -> core_facts_w W3.
Proof.
  intros Hov.
  destruct (trees_ok2 Hov) as (Htal & Htf & Hroom).
  pose proof (fbo_ok_w Htf Hroom) as Hfbo. pose proof fpend2_ok_w as Hfp.
  pose proof fill_ok_w as Hfill. destruct lm_ok as [Hins Hlm].
  exact (Build_core_facts_w W3 W3_prm W3_pos W3_frame W3_init W3_tune W3_dict_w
           (core_compress3_w Hfill Hins Hlm Htal Hfbo Hfp) (W3_still_w Hfill Hins Hlm Htal Hfbo Hfp)
           (core_live3_w Hfp) W3_full W3_params).
Qed.

Theorem core_theory_w : Zlib.proof.huffman.Overlay.overlay_statement -> core_w_stmt.
Proof. intros Hov. exists W3. exact (core_facts_w3 Hov). Qed.
