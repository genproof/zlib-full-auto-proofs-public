    + (* s->status = COMMENT_STATE *)
      Intros msgv2. subst o2.
      inversion Hc; subst s' z' o; clear Hc.
      sep_apply (dfull_flush_open_N s2 z2 p pin pout ish (rest_after z z2 R) msgv2 gv). Intros.
