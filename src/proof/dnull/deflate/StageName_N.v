Lemma stage_name_fix_N : forall (Espec : OracleKind) p pin pout ish R msgv gv flush s z hx W res,
  0 <= flush <= 5 -> c_deflate_name s z = Some res -> gz_ok (d_gzhead s) (p_gzhead p) hx W -> name_bytes s ->
  @semax DCS.CS Espec Delta_df_N
    (stage_pre_N p pin pout ish R msgv gv flush s z (hdr_res (d_gzhead s) (p_gzhead p) hx * W))%logic S_name
    (stage_post_N p pin pout ish R gv flush z (hdr_res (d_gzhead s) (p_gzhead p) hx * W)%logic res).
Proof.
  intros Espec p pin pout ish R msgv gv flush s z hx W res Hfl Hc Hgz Hnb.
  unfold stage_pre_N, stage_post_N, df_locals.
  cbv [S_name nth_stmt df_body f_deflate fn_body].
  sep_apply (dfull_gz_open_N s z p pin pout ish R msgv gv). Intros.
  unfold fr_nogz_N. Intros.
  forward.
  sep_apply (fr_nogz_fold_N s z p pin ish gv).
  sep_apply (dfull_gz_close_N s z z p pin pout ish R msgv gv); auto.
  destruct res as [[s' z'] o].
  forward_if (EX msgv' : val, PROP (o = None)
    LOCAL (temp _strm (p_strm p); temp _s (p_s p); temp _flush (vi flush); gvars gv)
    SEP (dfull_N s' z' p pin pout ish (rest_after z z' R) msgv' gv; deflate_globals gv;
         (hdr_res (d_gzhead s) (p_gzhead p) hx * W)%logic)).
  - (* NAME_STATE *)
    assert (Est : d_status s = NAME_STATE).
    { unfold NAME_STATE. open_dranges H1. apply repr_inj_signed; auto; rep_lia. }
    assert_PROP (Zlength R = z_avail_out z) as HR.
    { sep_apply (dfull_gz_open_N s z p pin pout ish R msgv gv). unfold out_space. entailer!. }
