Definition sn_inv_N (p : dptrs) (pin pout : val) (ish : share) (R : list val) (gv : globals) (flush : Z) (z : strm)
    (hsh : share) (h : gzh) (xp np cp : val) (W : mpred) (str : list Z) (e : (dstate * strm * Z) + (dstate * strm))
    : environ -> mpred :=
  EX s1 : dstate, EX z1 : strm, EX beg : Z, EX msgv1 : val,
  PROPx [runs (str_body h str) (s1, z1, beg) e; out_grow z z1; 0 <= beg <= Int64.max_unsigned]
  (LOCALx (sn_locals p flush beg gv)
  (SEPx [dfull_N s1 z1 p pin pout ish (rest_after z z1 R) msgv1 gv; deflate_globals gv;
         gzh_at hsh h (p_gzhead p) xp np cp; W])).

Definition sn_cont_N (p : dptrs) (pin pout : val) (ish : share) (R : list val) (gv : globals) (flush : Z) (z : strm)
