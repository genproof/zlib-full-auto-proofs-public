  intros. unfold loop_state_za_hz, loop_state_h_za_hz, locals_rep. f_equal. f_equal.
  unfold SEPx. extensionality rho. simpl. rewrite !sepcon_emp.
  unfold data_at_, field_at_. rewrite !sepcon_assoc. reflexivity.
Qed.

