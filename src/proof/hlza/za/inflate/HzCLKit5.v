       (overridePost (fall_post5_za_hz F m0 LEN_) (switch_ret_assert (case_post2_za_hz F m0)))) ->
  semax Delta_cases5_za_hz (loop_state_h_za_hz F m1 hv) cl_tables
    (overridePost (fall_post5_za_hz F m0 LEN_) (switch_ret_assert (case_post2_za_hz F m0))).

