Lemma cl_sep_eq_za_hz: forall F m hv,
  SEPx (A := environ) [mem_rep_za_hz F m; data_at Tsh t_code hv (f_vhere F); data_at_ Tsh t_code (f_vlast F);
        data_at_ Tsh (tarray tuchar 4) (f_vhbuf F)] = SEPx (cl_sep_za_hz F m hv).
Proof.
  intros. unfold cl_sep_za_hz, cl_strm_za_hz, mem_rep_za_hz, mem_rest_cl_za_hz. rewrite state_rep_cl.
  unfold SEPx. extensionality rho. simpl. apply pred_ext; cancel.
Qed.

