Definition updatewindow_spec3_za_hz :=
  DECLARE _updatewindow
  WITH gv: globals, shs: share, strmp: val, sv: reptype t_strm, sp: val, headp: val, winp: val,
       s: istate, ssh: share, p: val, n: Z, c: list val, e: Z, data: list Z, tr: list zev
  PRE [ tptr t_strm, tptr tuchar, tuint ]
    PROP (readable_share shs; stream_ok_val2_za_hz gv sv sp; swf s; readable_share ssh;
          0 <= Zlength data <= e; Zlength data <= Int.max_unsigned; e <= n; Zlength c = n;
          n <= Ptrofs.max_unsigned;
          sublist (e - Zlength data) e c = byte_vals data; bytes_ok data;
          i_win s = false -> winp = nullval; i_win s = false -> za_now tr + 2 ^ i_wbits s <= za_cap;
          is_pointer_or_null za_opaque)
    PARAMS (strmp; offset_val e p; Vint (Int.repr (Zlength data))) GLOBALS (gv)
    SEP (data_at shs t_strm sv strmp; state_rep gv sp strmp headp winp s; win_rep_za winp s;
         data_at ssh (tarray tuchar n) c p; za_res gv tr; zfuncs_za_hz gv)
  POST [ tint ]
    EX r: Z, EX winp': val,
    PROP ((r = 0 /\ (i_win s = true -> winp' = winp)) \/ (r = 1 /\ i_win s = false /\ winp' = nullval))
    RETURN (Vint (Int.repr r))
    SEP (data_at shs t_strm sv strmp;
         state_rep gv sp strmp headp winp' (if r =? 0 then set_i_win (updatewindow s data) true else s);
         win_rep_za winp' (if r =? 0 then set_i_win (updatewindow s data) true else s);
         data_at ssh (tarray tuchar n) c p; za_res gv (tr ++ uw_ev s r); zfuncs_za_hz gv).

