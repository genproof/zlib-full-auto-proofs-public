(* the lemma of the case at index i (mode Y) *)
Definition case_ok_za_hz {Espec: OracleKind} (F: frame) (Y: Z) (i: nat) : Prop :=
  forall m', m_mode m' = Y -> m_leave m' = 0 -> mwf_za m' ->
    semax Delta_inflate_za_hz (loop_state_za_hz F m') (seq_of_labeled_statement (ls_drop i inflate_LS))
