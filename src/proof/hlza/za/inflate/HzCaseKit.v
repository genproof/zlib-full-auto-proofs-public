(* the end of case i's body when it falls through into mode Y: the machine m' with the same outcome
   of the pass *)
Definition fall_post_za_hz (F: frame) (m: mst) (Y: Z) : environ -> mpred :=
  EX m': mst,
    !! (stepf (f_flush F) lenfix_list distfix_list m = stepf (f_flush F) lenfix_list distfix_list m' /\
        m_mode m' = Y /\ m_leave m' = 0 /\ mwf_za m') && loop_state_za_hz F m'.

Lemma case_post_eq_za_hz: forall F m m',
  stepf (f_flush F) lenfix_list distfix_list m = stepf (f_flush F) lenfix_list distfix_list m' ->
  case_post_za_hz F m = case_post_za_hz F m'.
Proof. intros F m m' E. unfold case_post_za_hz. rewrite E. reflexivity. Qed.

Lemma case_fallthrough_za_hz {Espec: OracleKind} (F: frame) (m: mst) (Y: Z) (i: nat):
  (i < 32)%nat ->
  case_ok_za_hz F Y (S i) ->
  semax Delta_inflate_za_hz (loop_state_za_hz F m) (case_body i)
    (overridePost (fall_post_za_hz F m Y) (switch_ret_assert (case_post_za_hz F m))) ->
  semax Delta_inflate_za_hz (loop_state_za_hz F m) (seq_of_labeled_statement (ls_drop i inflate_LS))
    (switch_ret_assert (case_post_za_hz F m)).
Proof.
  intros Hi HY HB. rewrite seq_split by lia.
  eapply semax_seq; [exact HB | ].
  unfold fall_post_za_hz. Intros m'.
  apply semax_extract_prop. intros (E & HM & HL & W).
  rewrite (case_post_eq_za_hz F m m' E).
  apply HY; auto.
Qed.

