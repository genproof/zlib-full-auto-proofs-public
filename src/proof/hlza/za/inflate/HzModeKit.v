Lemma loop_state_split_za_hz: forall F m, loop_state_za_hz F m = loop_state_m_za_hz F m (zv (m_mode m)).
Proof.
  intros. unfold loop_state_za_hz, loop_state_m_za_hz. rewrite mem_rep_split_za_hz.
  f_equal. unfold SEPx. simpl. rewrite !sepcon_assoc. reflexivity.
Qed.

Lemma loop_state_set_mode_za_hz: forall F m md, loop_state_za_hz F (set_mode m md) = loop_state_m_za_hz F m (zv md).
Proof. intros. rewrite loop_state_split_za_hz. reflexivity. Qed.

(* state->mode = md; *)
Lemma semax_store_mode_za_hz {Espec: OracleKind} (F: frame) (m: mst) (md: Z):
  semax Delta_inflate_za_hz (loop_state_za_hz F m)
    (Sassign (Efield (Ederef (Etempvar _state (tptr (Tstruct _inflate_state noattr)))
                       (Tstruct _inflate_state noattr)) _mode tint)
       (Econst_int (Int.repr md) tint))
    (normal_ret_assert (loop_state_za_hz F (set_mode m md))).
Proof.
  rewrite loop_state_set_mode_za_hz, loop_state_split_za_hz. unfold loop_state_m_za_hz.
  abbreviate_semax.
  forward.
  entailer!.
Qed.

(* mwf after a change between the modes that need only the decoding tables (LEN_, LEN, LIT), from a
   decoding mode.  Do not prove such side goals with `apply mwf_set_mode; auto`: it took > 5 min. *)
Lemma mwf_set_mode_tables_za_hz: forall m md,
  mwf_za m -> decode_mode (m_mode m) -> md = LEN_ \/ md = LEN \/ md = LIT -> mwf_za (set_mode m md).
Proof.
  intros m md W D Hmd.
  assert (Hr: HEAD <= md <= SYNC) by (unfold HEAD, SYNC, LEN_, LEN, LIT in *; lia).
  pose proof (md_tables _ (mw_md_za _ W) D) as T.
  assert (Hne: forall P: Prop,
    md = LENLENS \/ md = CODELENS \/ md = LENEXT \/ md = DIST \/ md = DISTEXT \/ md = MATCH -> P).
  { intros P H. exfalso. unfold LENLENS, CODELENS, LENEXT, DIST, DISTEXT, MATCH, LEN_, LEN, LIT in *. lia. }
  assert (O: m_out m = m_aout m).
  { apply mwf_out_eq_za; [exact W | | | ]; intro E; rewrite E in D;
      unfold decode_mode, LENGTH, DONE, BAD, LEN_, LEN, LENEXT, DIST, DISTEXT, MATCH, LIT in D; lia. }
  apply (mwf_set_mode_za m md W Hr);
    [ intro; apply Hne; tauto | intro; apply Hne; tauto | intros _; exact T
    | intro; apply Hne; tauto | intro; apply Hne; tauto | intro; apply Hne; tauto
    | intro; apply Hne; tauto | intro; apply Hne; tauto | intro; apply Hne; tauto
    | intro; apply Hne; tauto | intro; apply Hne; tauto | left; exact O ].
Qed.

