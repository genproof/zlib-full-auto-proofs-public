(** * Lemma (i) for lit_bufsize >= 4096: the bound from the facts on the unlimited Huffman depths

    [overlay_bound_d]: for a block satisfying [block_facts_d] (facts on the unlimited Huffman depths [dd]/[dd0] of
    the literal/length and distance codes) the header, the symbols coded with the depths, and an extra amount [X]
    up to [slack L] (the repair overhead of gen_bitlen's length limit) fit: after the first k symbols the bit
    position is at most 8 * (L + 3k).
    The proof is a per-code certificate (the dual of a linear program over the facts), one per lit_bufsize
    4096 .. 32768, checked by computation; the depths range over 1..30 (the Fibonacci caps exclude the larger
    ones, the check skips a depth whose cap is below 1).  The certificates are generated by
    docs/huffman-gen/certs.py (gen_certd.py; linear program optima: 17020.2, 31777.0, 61320.3, 120411.5 bits). *)

