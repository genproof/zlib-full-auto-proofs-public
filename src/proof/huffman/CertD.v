(** ** The slack: the repair overhead the bound tolerates *)

Definition slack (L : Z) : Z :=
  if L =? 4096 then 15360          (* 15 L / 4 *)
  else if L =? 8192 then 32768     (* 4 L *)
  else if L =? 16384 then 67584    (* 33 L / 8 *)
  else if L =? 32768 then 139264   (* 17 L / 4 *)
  else 0.

(** ** A fast Fibonacci for the checks *)

Fixpoint fibp (n : nat) : Z * Z := match n with O => (0, 1) | S m => let (a, b) := fibp m in (b, a + b) end.

Lemma fibp_ok : forall n, fibp n = (fibn n, fibn (S n)).
Proof.
  induction n as [|m IH]; [reflexivity|]. simpl fibp. rewrite IH.
  change (fibn (S (S m))) with (fibn (S m) + fibn m). f_equal. lia.
Qed.

Definition fibf (d : Z) : Z := fst (fibp (Z.to_nat d)).

Lemma fibf_ok : forall d, fibf d = fib d.
Proof. intros d. unfold fibf, fib. rewrite fibp_ok. reflexivity. Qed.

(** ** Certificates *)

Record certd := mkCertD {
  cd_L : Z; cd_D : Z;
  cd_lam : Z; cd_ml : Z; cd_md : Z; cd_eta : Z; cd_kap : Z;
  cd_P : list Z;     (* u = 0..35 *)
  cd_R : list Z;     (* v = 0..43 *)
  cd_nul : list Z;   (* 286 *)
  cd_nud : list Z    (* 30 *)
}.

Section ChecksD.
Variable C : certd.

Definition capd (l : Z) : Z := Z.min (cd_L C - 1) ((cd_L C + 1) / fibf (l + 1)).

Definition al_d (c l : Z) : Z :=
  (if 257 <=? c then Znth (l + xlb c) (cd_P C) else 0) - cd_lam C * (l - stl c) - cd_eta C +
  (if 257 <=? c then cd_kap C else 0).
Definition bl_d (l : Z) : Z := - cd_ml C * 2 ^ (30 - l).
Definition ad_d (d l : Z) : Z := Znth (l + xdb d) (cd_R C) - cd_lam C * (l - 5) - cd_kap C.
Definition bd_d (l : Z) : Z := - cd_md C * 2 ^ (30 - l).

Definition chkd_pr : bool :=
  forallb (fun u => forallb (fun v => cd_D C * Z.max 0 (u + v - 24) <=? Znth u (cd_P C) + Znth v (cd_R C))
                            (zseq 0 44)) (zseq 0 36).

Definition chkd_l1 (c : Z) : bool :=
  forallb (fun l => (capd l <? 1) ||
     ((al_d c l + bl_d l <=? Znth c (cd_nul C)) && (al_d c l * capd l + bl_d l <=? Znth c (cd_nul C))))
    (zseq 1 30).

Definition chkd_lit : bool :=
  forallb (fun c => (c =? 256) || (0 <=? Znth c (cd_nul C))) (zseq 0 286) && forallb chkd_l1 (zseq 0 286).

Definition chkd_d1 (d : Z) : bool :=
  forallb (fun l => ((capd l <? 1) ||
     ((ad_d d l + bd_d l <=? Znth d (cd_nud C)) && (ad_d d l * capd l + bd_d l <=? Znth d (cd_nud C)))) &&
     (bd_d l <=? Znth d (cd_nud C)))
    (zseq 1 30).

Definition chkd_dist : bool :=
  forallb (fun d => 0 <=? Znth d (cd_nud C)) (zseq 0 30) && forallb chkd_d1 (zseq 0 30).

Definition chkd_signs : bool :=
  (0 <? cd_D C) && (0 <=? cd_lam C) && (cd_lam C <=? cd_D C) && (0 <=? cd_md C) && (0 <=? cd_eta C) &&
  (4096 <=? cd_L C) && (cd_L C <=? 32768).

Definition finald : Z :=
  (cd_D C - cd_lam C) * 2283 - cd_lam C + 2 ^ 30 * (cd_ml C + cd_md C) + cd_eta C * cd_L C +
  zsum 286 (fun c => Znth c (cd_nul C)) + zsum 30 (fun d => Znth d (cd_nud C)).

Definition chkd_final : bool := finald <=? cd_D C * (8 * cd_L C - 10 - slack (cd_L C)).

Definition certd_ok : bool := chkd_signs && chkd_pr && chkd_lit && chkd_dist && chkd_final.

End ChecksD.

(** ** Soundness *)

Lemma capd_ok : forall C f l, 1 <= l -> 1 <= f -> f <= cd_L C - 1 -> f * fib (l + 1) <= cd_L C + 1 -> f <= capd C l.
Proof.
  intros C f l Hl Hf1 Hf2 Hcap. unfold capd. rewrite fibf_ok.
  assert (H1 : fib 2 <= fib (l + 1)) by (apply fib_mono; lia).
  change (fib 2) with 1 in H1. apply Z.min_glb; [lia|]. apply Z.div_le_lower_bound; lia.
Qed.

Lemma filter_In_pos : forall {A} (f : A -> bool) l x, In x l -> f x = true -> 0 < Zlength (filter f l).
Proof.
  intros A f l x Hx Hf. induction l as [|y l IH]; [destruct Hx|]. rewrite Zlength_filter_cons.
  assert (H0 := Zlength_nonneg (filter f l)). destruct Hx as [<-|Hx].
  - rewrite Hf. lia.
  - assert (H := IH Hx). destruct (f y); lia.
Qed.

Lemma fib_25 : fib 25 = 75025.
Proof. rewrite <- fibf_ok. vm_compute. reflexivity. Qed.

(** ** Symbol keys (local copies, independent of the certificates of Cert.v) *)

Definition dkd (x : Z * Z) : Z := if fst x =? 0 then 30 else d_code (fst x - 1).

Lemma lrange : forall x, valid_sym (fst x) (snd x) ->
  (fst x = 0 /\ lcode_of x = snd x /\ 0 <= snd x <= 255) \/
  (fst x <> 0 /\ lcode_of x = Znth (snd x) length_code_tab + 257 /\ 0 <= Znth (snd x) length_code_tab <= 28 /\
   0 <= Znth (Znth (snd x) length_code_tab) extra_lbits <= 5).
Proof.
  intros x [Hl Hd]. unfold lcode_of. destruct (Z.eqb_spec (fst x) 0) as [E|E]; [left; auto|right].
  destruct (length_code_facts (snd x) Hl) as [A [B _]]. unfold LITERALS. split; auto. split; [lia|]. auto.
Qed.

Lemma drange : forall x, valid_sym (fst x) (snd x) ->
  (fst x = 0 /\ dkd x = 30) \/
  (fst x <> 0 /\ dkd x = d_code (fst x - 1) /\ 0 <= d_code (fst x - 1) <= 29 /\
   0 <= Znth (d_code (fst x - 1)) extra_dbits <= 13).
Proof.
  intros x [Hl Hd]. unfold dkd. destruct (Z.eqb_spec (fst x) 0) as [E|E]; [left; auto|right].
  destruct (dist_code_facts (fst x - 1) ltac:(lia)) as [A [B _]]. auto.
Qed.

Lemma filter_none : forall {A} (f : A -> bool) l, (forall x, In x l -> f x = false) -> filter f l = [].
Proof. intros A f l H. induction l as [|x l IH]; simpl; [reflexivity|]. rewrite H by (left; auto). apply IH. intros; apply H; right; auto. Qed.

Lemma prefix_all : forall (cf w : Z * Z -> Z) Dd l, 0 < Dd ->
  (forall x, In x l -> Dd * (cf x - 24) <= w x /\ 0 <= w x) ->
  forall k, Dd * (hsum (map cf (firstn k l)) - 24 * Z.of_nat (length (firstn k l))) <= hsum (map w l).
Proof.
  intros cf w Dd l HD H. induction l as [|x l IH]; intros k.
  - destruct k; simpl; lia.
  - destruct k as [|k].
    + assert (Hn : 0 <= hsum (map w (x :: l))) by (apply sumZ_nonneg; intros y Hy; apply H; auto).
      cbn [firstn length map HuffAbs.sumZ] in *. lia.
    + cbn [firstn map length HuffAbs.sumZ]. assert (IH' := IH ltac:(intros; apply H; right; auto) k).
      destruct (H x (or_introl eq_refl)) as [H1 H2]. nia.
Qed.

Section SoundD.
Variable C : certd.
Hypothesis HC : certd_ok C = true.
Variables (L b0 : Z) (syms : list (Z * Z)) (dd dd0 : list Z) (hdr : Z).
Hypothesis HB : block_facts_d L b0 syms dd dd0 hdr.
Hypothesis HL : L = cd_L C.

Let F c := lfreq syms c.
Let G d := dfreq syms d.

Lemma HCs : chkd_signs C = true /\ chkd_pr C = true /\ chkd_lit C = true /\ chkd_dist C = true /\
            chkd_final C = true.
Proof. unfold certd_ok in HC. repeat rewrite andb_true_iff in HC. tauto. Qed.

Lemma signs_d : 0 < cd_D C /\ 0 <= cd_lam C /\ cd_lam C <= cd_D C /\ 0 <= cd_md C /\ 0 <= cd_eta C /\
  4096 <= cd_L C <= 32768.
Proof.
  destruct HCs as [H1 _]. unfold chkd_signs in H1. repeat rewrite andb_true_iff in H1.
  rewrite !Z.leb_le, Z.ltb_lt in H1. lia.
Qed.

(** *** Symbols *)

Lemma vall : forall x, In x syms -> valid_sym (fst x) (snd x).
Proof. exact (bd_valid _ _ _ _ _ _ HB). Qed.

Lemma lkey_b : forall x, In x syms -> 0 <= lcode_of x < 286.
Proof. intros x Hx. destruct (lrange x (vall x Hx)) as [[_ [-> ?]]|[_ [-> [? _]]]]; lia. Qed.

Lemma dkey_b : forall x, In x syms -> 0 <= dkd x < 31.
Proof. intros x Hx. destruct (drange x (vall x Hx)) as [[_ ->]|[_ [-> [? _]]]]; lia. Qed.

Definition cl (j : Z) : Z := Zlength (filter (fun x => lcode_of x =? j) syms).
Definition cdk (d : Z) : Z := Zlength (filter (fun x => dkd x =? d) syms).

Lemma F_cl : forall j, F j = cl j + (if j =? END_BLOCK then 1 else 0).
Proof. reflexivity. Qed.

Lemma cl_256 : cl 256 = 0.
Proof.
  unfold cl. rewrite filter_none; [reflexivity|]. intros x Hx.
  destruct (lrange x (vall x Hx)) as [[_ [-> ?]]|[_ [-> [? _]]]]; apply Z.eqb_neq; lia.
Qed.

Lemma cdk_G : forall d, 0 <= d < 30 -> cdk d = G d.
Proof.
  intros d Hd. unfold cdk, G, dfreq. f_equal. apply filter_ext_in. intros x Hx. unfold dkd.
  destruct (Z.eqb_spec (fst x) 0).
  - rewrite (proj2 (Z.eqb_neq 30 d)) by lia. reflexivity.
  - reflexivity.
Qed.

Lemma F_nn : forall c, 0 <= F c.
Proof. intros c. rewrite F_cl. unfold cl. assert (H := Zlength_nonneg (filter (fun x => lcode_of x =? c) syms)). destruct (c =? END_BLOCK); lia. Qed.

Lemma G_nn : forall d, 0 <= G d.
Proof. intros d. apply Zlength_nonneg. Qed.

Lemma F_END : F 256 = 1.
Proof. rewrite F_cl, cl_256. reflexivity. Qed.

Definition nmd : Z := hsum (map (fun x => if fst x =? 0 then 0 else 1) syms).

Lemma sumF_d : zsum 286 F = Zlength syms + 1.
Proof.
  assert (Hk := sum_by_key lcode_of (fun _ => 1) 286 syms lkey_b). rewrite hsum_ones in Hk.
  rewrite zsum_rs in Hk |- *. change (Z.to_nat 286) with 286%nat in *.
  rewrite (rs_ext _ 0 F (fun j => 1 * Zlength (filter (fun x => lcode_of x =? j) syms) + (if j =? 256 then 1 else 0)))
    by (intros j Hj; rewrite F_cl; unfold cl, END_BLOCK; lia).
  rewrite rs_add, rs_ind by (simpl; lia). lia.
Qed.

Definition Mtd (j : Z) : Z := if 257 <=? j then F j else 0.

Lemma nmd_l : nmd = zsum 286 Mtd.
Proof.
  unfold nmd. transitivity (hsum (map (fun x => (fun j => if 257 <=? j then 1 else 0) (lcode_of x)) syms)).
  - f_equal. apply map_ext_in. intros x Hx.
    destruct (lrange x (vall x Hx)) as [[E [-> ?]]|[E [-> [? _]]]].
    + rewrite E. simpl. destruct (Z.leb_spec 257 (snd x)); lia.
    + rewrite (proj2 (Z.eqb_neq _ _) E). destruct (Z.leb_spec 257 (Znth (snd x) length_code_tab + 257)); lia.
  - assert (Hk := sum_by_key lcode_of (fun j => if 257 <=? j then 1 else 0) 286 syms lkey_b). cbv beta in Hk.
    rewrite Hk. rewrite !zsum_rs. apply rs_ext. intros j Hj.
    unfold Mtd. destruct (Z.leb_spec 257 j); [|lia]. rewrite F_cl. replace (j =? END_BLOCK) with false
      by (symmetry; apply Z.eqb_neq; unfold END_BLOCK; lia). fold (cl j). lia.
Qed.

Lemma nmd_d : nmd = zsum 30 G.
Proof.
  unfold nmd. transitivity (hsum (map (fun x => (fun d => if d =? 30 then 0 else 1) (dkd x)) syms)).
  - f_equal. apply map_ext_in. intros x Hx.
    destruct (drange x (vall x Hx)) as [[E ->]|[E [-> [? _]]]].
    + rewrite E. reflexivity.
    + rewrite (proj2 (Z.eqb_neq _ _) E). destruct (Z.eqb_spec (d_code (fst x - 1)) 30); lia.
  - assert (Hk := sum_by_key dkd (fun d => if d =? 30 then 0 else 1) 31 syms dkey_b). cbv beta in Hk.
    rewrite Hk. rewrite !zsum_rs.
    change (Z.to_nat 31) with (S 30). rewrite rs_snoc. simpl (0 + Z.of_nat 30). rewrite Z.eqb_refl.
    change (Z.to_nat 30) with 30%nat. rewrite Z.mul_0_l, Z.add_0_r. apply rs_ext. intros d Hd.
    replace (d =? 30) with false by (symmetry; apply Z.eqb_neq; lia). fold (cdk d). rewrite cdk_G by lia. lia.
Qed.

Lemma nmd_le : nmd <= Zlength syms.
Proof.
  unfold nmd. rewrite <- hsum_ones. apply hsum_map_le. intros x _. destruct (fst x =? 0); lia.
Qed.

Lemma n_b : 1 <= Zlength syms <= L - 1.
Proof. exact (bd_n _ _ _ _ _ _ HB). Qed.

Lemma F_le_d : forall c, 0 <= c < 286 -> c <> 256 -> F c <= L - 1.
Proof.
  intros c Hc Hne. assert (H2 := rs_two 286 0 F c 256 (fun i _ => F_nn i) ltac:(simpl; lia) ltac:(simpl; lia) Hne).
  change (rs 0 286 F) with (zsum 286 F) in H2. rewrite sumF_d, F_END in H2.
  assert (H3 := n_b). lia.
Qed.

Lemma G_le_d : forall d, 0 <= d < 30 -> G d <= L - 1.
Proof.
  intros d Hd. assert (H1 := rs_single 30 0 G d (fun i _ => G_nn i) ltac:(simpl; lia)).
  change (rs 0 30 G) with (zsum 30 G) in H1. rewrite <- nmd_d in H1. assert (H2 := nmd_le). assert (H3 := n_b). lia.
Qed.

Lemma L_range : 4096 <= L <= 32768.
Proof.
  destruct (bd_L _ _ _ _ _ _ HB) as [ml [Hml ->]].
  assert (ml = 6 \/ ml = 7 \/ ml = 8 \/ ml = 9) by lia.
  repeat (destruct H as [->|H]; [simpl; lia|]). subst. simpl. lia.
Qed.

(** *** Extracting the checks *)

Lemma chkd_pr_spec : forall u v, 0 <= u <= 35 -> 0 <= v <= 43 ->
  cd_D C * Z.max 0 (u + v - 24) <= Znth u (cd_P C) + Znth v (cd_R C).
Proof.
  intros u v Hu Hv. destruct HCs as [_ [H2 _]]. unfold chkd_pr in H2.
  assert (E := forallb_zseq _ _ _ H2 u ltac:(simpl; lia)). cbv beta in E.
  assert (E2 := forallb_zseq _ _ _ E v ltac:(simpl; lia)). cbv beta in E2. apply Z.leb_le in E2. exact E2.
Qed.

Lemma nul_nn : forall c, 0 <= c < 286 -> c <> 256 -> 0 <= Znth c (cd_nul C).
Proof.
  intros c Hc Hne. destruct HCs as [_ [_ [H3 _]]]. unfold chkd_lit in H3. apply andb_true_iff in H3.
  destruct H3 as [H3 _]. assert (E := forallb_zseq _ _ _ H3 c ltac:(simpl; lia)). cbv beta in E.
  apply orb_true_iff in E. destruct E as [E|E]; [apply Z.eqb_eq in E; lia|apply Z.leb_le in E; exact E].
Qed.

Lemma chkd_l1_spec : forall c l, 0 <= c < 286 -> 1 <= l <= 30 -> 1 <= capd C l ->
  al_d C c l + bl_d C l <= Znth c (cd_nul C) /\ al_d C c l * capd C l + bl_d C l <= Znth c (cd_nul C).
Proof.
  intros c l Hc Hl Hcap. destruct HCs as [_ [_ [H3 _]]]. unfold chkd_lit in H3. apply andb_true_iff in H3.
  destruct H3 as [_ H3]. assert (E := forallb_zseq _ _ _ H3 c ltac:(simpl; lia)). unfold chkd_l1 in E.
  assert (E2 := forallb_zseq _ _ _ E l ltac:(simpl; lia)). cbv beta in E2.
  apply orb_true_iff in E2. destruct E2 as [E2|E2]; [apply Z.ltb_lt in E2; lia|].
  apply andb_true_iff in E2. rewrite !Z.leb_le in E2. exact E2.
Qed.

Lemma nud_nn : forall d, 0 <= d < 30 -> 0 <= Znth d (cd_nud C).
Proof.
  intros d Hd. destruct HCs as [_ [_ [_ [H5 _]]]]. unfold chkd_dist in H5. apply andb_true_iff in H5.
  destruct H5 as [H5 _]. assert (E := forallb_zseq _ _ _ H5 d ltac:(simpl; lia)). cbv beta in E.
  apply Z.leb_le in E. exact E.
Qed.

Lemma chkd_d1_spec : forall d l, 0 <= d < 30 -> 1 <= l <= 30 ->
  (1 <= capd C l ->
   ad_d C d l + bd_d C l <= Znth d (cd_nud C) /\ ad_d C d l * capd C l + bd_d C l <= Znth d (cd_nud C)) /\
  bd_d C l <= Znth d (cd_nud C).
Proof.
  intros d l Hd Hl. destruct HCs as [_ [_ [_ [H5 _]]]]. unfold chkd_dist in H5. apply andb_true_iff in H5.
  destruct H5 as [_ H5]. assert (E := forallb_zseq _ _ _ H5 d ltac:(simpl; lia)). unfold chkd_d1 in E.
  assert (E2 := forallb_zseq _ _ _ E l ltac:(simpl; lia)). cbv beta in E2.
  apply andb_true_iff in E2. destruct E2 as [E2 E3]. apply Z.leb_le in E3. split; [|exact E3].
  intros Hcap. apply orb_true_iff in E2. destruct E2 as [E2|E2]; [apply Z.ltb_lt in E2; lia|].
  apply andb_true_iff in E2. rewrite !Z.leb_le in E2. exact E2.
Qed.

Lemma finald_spec : finald C <= cd_D C * (8 * cd_L C - 10 - slack (cd_L C)).
Proof. destruct HCs as [_ [_ [_ [_ H8]]]]. apply Z.leb_le in H8. exact H8. Qed.

(** *** The excess cost of the symbols *)

Lemma ldep : forall c, 0 <= c < 286 -> 0 <= Znth c dd <= 30.
Proof. intros c Hc. apply (bd_llen _ _ _ _ _ _ HB c). unfold L_CODES; lia. Qed.
Lemma ddep : forall d, 0 <= d < 30 -> 0 <= Znth d dd0 <= 30.
Proof. intros d Hd. apply (bd_dlen _ _ _ _ _ _ HB d). unfold D_CODES; lia. Qed.

(** A used literal has depth at most 23: its frequency is at least 1 and fib 25 > L + 1. *)
Lemma lit_dep : forall x, In x syms -> fst x = 0 -> Znth (snd x) dd <= 23.
Proof.
  intros x Hx E0. destruct (lrange x (vall x Hx)) as [[_ [El Hr]]|[E _]]; [|contradiction].
  assert (Hpos : 0 < lfreq syms (snd x)).
  { assert (Ht : (fun y => lcode_of y =? snd x) x = true) by (cbv beta; rewrite El; apply Z.eqb_refl).
    assert (H := filter_In_pos (fun y => lcode_of y =? snd x) syms x Hx Ht).
    unfold lfreq. destruct (snd x =? END_BLOCK); lia. }
  assert (Hcap := bd_cap_l _ _ _ _ _ _ HB (snd x) ltac:(unfold L_CODES; lia) Hpos).
  assert (HLr := L_range). destruct (Z_le_gt_dec (Znth (snd x) dd) 23) as [|Hgt]; auto. exfalso.
  assert (Hf : fib 25 <= fib (Znth (snd x) dd + 1)) by (apply fib_mono; lia). rewrite fib_25 in Hf.
  assert (lfreq syms (snd x) * fib (Znth (snd x) dd + 1) >= 1 * 75025) by (apply Zmult_ge_compat; lia). lia.
Qed.

Definition PiD (c : Z) : Z := if 257 <=? c then Znth (Znth c dd + xlb c) (cd_P C) else 0.
Definition RhoD (d : Z) : Z := Znth (Znth d dd0 + xdb d) (cd_R C).
Definition RkD (d : Z) : Z := if d =? 30 then 0 else RhoD d.
Definition wd (x : Z * Z) : Z := PiD (lcode_of x) + RkD (dkd x).

Lemma sym_wd : forall x, In x syms -> cd_D C * (sym_cost dd dd0 (fst x) (snd x) - 24) <= wd x /\ 0 <= wd x.
Proof.
  intros x Hx. assert (HD := proj1 signs_d). unfold wd.
  destruct (lrange x (vall x Hx)) as [[E0 [El Hr]]|[E0 [El [Hj Hxl]]]];
  destruct (drange x (vall x Hx)) as [[E1 Ed]|[E1 [Ed [Hd Hxd]]]]; try congruence.
  - rewrite El, Ed. unfold PiD, RkD. replace (257 <=? snd x) with false by (symmetry; apply Z.leb_gt; lia).
    rewrite Z.eqb_refl. unfold sym_cost. rewrite E0, Z.eqb_refl.
    assert (H23 := lit_dep x Hx E0). nia.
  - rewrite El, Ed. set (j := Znth (snd x) length_code_tab) in *. set (d := d_code (fst x - 1)) in *.
    unfold PiD, RkD, RhoD, xlb, xdb. replace (257 <=? j + 257) with true by (symmetry; apply Z.leb_le; lia).
    replace (d =? 30) with false by (symmetry; apply Z.eqb_neq; lia). replace (j + 257 - 257) with j by lia.
    unfold sym_cost. rewrite (proj2 (Z.eqb_neq _ _) E0). fold j d.
    assert (H1 := ldep (j + 257) ltac:(lia)). assert (H2 := ddep d ltac:(lia)).
    assert (Hu : 0 <= Znth (j + 257) dd + Znth j extra_lbits <= 35) by lia.
    assert (Hv : 0 <= Znth d dd0 + Znth d extra_dbits <= 43) by lia.
    assert (Hpr := chkd_pr_spec (Znth (j + 257) dd + Znth j extra_lbits) (Znth d dd0 + Znth d extra_dbits) Hu Hv).
    assert (0 <= cd_D C * Z.max 0 (Znth (j + 257) dd + Znth j extra_lbits + (Znth d dd0 + Znth d extra_dbits) - 24))
      by (apply Z.mul_nonneg_nonneg; lia).
    assert (cd_D C * (Znth (j + 257) dd + Znth j extra_lbits + Znth d dd0 + Znth d extra_dbits - 24) <=
            cd_D C * Z.max 0 (Znth (j + 257) dd + Znth j extra_lbits + (Znth d dd0 + Znth d extra_dbits) - 24))
      by (apply Z.mul_le_mono_nonneg_l; lia).
    lia.
Qed.

Lemma cost_sum_h : forall l, cost_sum dd dd0 l = hsum (map (fun x => sym_cost dd dd0 (fst x) (snd x)) l).
Proof. intros l; induction l as [|[d c] l IH]; [reflexivity|]. simpl. rewrite IH. reflexivity. Qed.

Lemma wsum_d : hsum (map wd syms) = zsum 286 (fun c => F c * PiD c) + zsum 30 (fun d => G d * RhoD d).
Proof.
