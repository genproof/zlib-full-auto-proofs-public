Definition KlD (c : Z) : Z := if Znth c dd =? 0 then 0 else 2 ^ (30 - Znth c dd).
Definition KdD (d : Z) : Z := if Znth d dd0 =? 0 then 0 else 2 ^ (30 - Znth d dd0).

