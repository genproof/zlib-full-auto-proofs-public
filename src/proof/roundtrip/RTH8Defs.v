(* The parts of inflate()'s body against RTH8Spec.inflate_spec8 (an application gz_header whose absent fields stay
   undefined).

   Two worlds meet in this proof:
   - the header world (RTHLoop.v, RTHCase.v): in the header modes HEAD .. HCRC the header is the partial
     RTHSpec.head_rep6, held next to the headless loop state RTHLoop.loop_stateH;
   - the headless world after the header (src/proof/hl/, generated by docs/port-hl/port.py): Spec5's switch cases
     DICTID .. SYNC, its loop and exit and inflate_fast, with Loop.head_part replaced by the atom hnoneH = emp; the
     header is a frame the caller holds: RTH8Spec.head_rep8a once the header is passed.
   Their loop states are the same predicate (mem_rep_hl and RTHLoop.mem_repH are convertible).

   The statements proved by the parts:
   - cases8_all: the header cases with a header that passes in this call (RTH8Spec.hpass8): a case ends in a
     header mode (head_rep6) or past the header, with head_rep8a;
   - cases_nh: the headless cases of the modes after the header (DICTID .. SYNC);
   - loop_part8_stmt: the headless main loop over machines that stay out of the header modes;
   - stepf2_nh_stmt, leave_nh_stmt: one pass from a mode after the header stays there and keeps the header model
     and the flags (so the frame head_rep8a stays valid), and so does the exit;
   - rth8_delta_stmt: the headless inflate_fast specification is stronger than Spec5's (inflate_fast_spec3), so
     Spec5's proofs move into the context of the headless one. *)
