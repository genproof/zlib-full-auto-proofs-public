Local Open Scope logic.

(* ---------------------------------------------------------------------------------------------- *)
(* the header of a machine                                                                        *)

(* past the header: RTH8Spec.head_rep8a *)
Definition hd8a (F: frame) (m: mst) : mpred :=
  head_rep8a (f_hsh F) (f_headp F) (f_xb F) (f_nb F) (f_cb F) (m_s m) (m_h m).

(* in a header mode the partial head_rep6, past the header head_rep8a *)
Definition hd8 (F: frame) (m: mst) : mpred :=
  if hdr_mode (m_mode m) then hd6 F m else hd8a F m.

(* ---------------------------------------------------------------------------------------------- *)
(* the header cases                                                                               *)

(* after a pass of a header case: the headless loop state and the header *)
Definition post8 (F: frame) (m: mst) : environ -> mpred :=
  loop_stateH F m * (fun _ => hd8 F m).

Definition case_post8 (F: frame) (m: mst) : ret_assert :=
  {| RA_normal := EX m': mst, !! (stepf2 (f_flush F) lenfix_list distfix_list m = IBrk m') && post8 F m';
     RA_break := FF;
     RA_continue := FF;
     RA_return := fun _ _ => FF |}.

(* the lemma of header case i (mode Y) with a header attached, on a call that passes the header (hpass8) *)
Definition case_ok8 {Espec: OracleKind} (F: frame) (Y: Z) (i: nat) : Prop :=
  forall m n, m_mode m = Y -> m_leave m = 0 -> mwf3 m -> hd_ok F m -> i_head (m_s m) = true ->
    hpass8 (f_flush F) (S n) m ->
    semax Delta_cases5 (loop_stateH F m * (fun _ => hdr_tok F m * hd6 F m))
      (seq_of_labeled_statement (ls_drop i inflate_LS))
      (frame_ret_assert (switch_ret_assert (case_post8 F m)) (fun _ => hdr_tok F m)).

(* every header case *)
Definition cases8_all : Prop :=
  forall {Espec: OracleKind} (F: frame), frame_ok5 F -> forall i, (i <= 8)%nat -> case_ok8 F (IM.HEAD + Z.of_nat i) i.

(* ---------------------------------------------------------------------------------------------- *)
(* the headless world after the header                                                            *)

(* the headless cases of the modes DICTID .. SYNC (the switch's labels 9 .. 31) *)
Definition cases_nh : Prop :=
  forall {Espec: OracleKind} (F: frame), frame_ok5 F ->
    forall i, (9 <= i < 32)%nat -> case_ok5_hl F (IM.HEAD + Z.of_nat i) i.

(* one pass from a mode after the header: still after the header, the same header model and flags *)
Definition stepf2_nh_stmt : Prop :=
  forall flush m, mwf3 m -> m_leave m = 0 -> hdr_mode (m_mode m) = false ->
  match stepf2 flush lenfix_list distfix_list m with
  | IBrk m' => hdr_mode (m_mode m') = false /\ m_h m' = m_h m /\ i_flags (m_s m') = i_flags (m_s m)
  | IRet _ m' => hdr_mode (m_mode m') = false /\ m_h m' = m_h m /\ i_flags (m_s m') = i_flags (m_s m)
  end.

(* the exit inf_leave from a mode after the header: the same *)
Definition leave_nh_stmt : Prop :=
  forall flush m res, mwf3 m -> out_inv m -> win_inv5 (m_s m) -> inf_leave flush m res ->
  hdr_mode (m_mode m) = false ->
  hdr_mode (m_mode (r_m res)) = false /\ i_flags (m_s (r_m res)) = i_flags (m_s m).

(* the headless main loop from m0, over machines that stay out of the header modes (P implies it) *)
Definition loop_part8_stmt : Prop :=
  forall {Espec: OracleKind} (F: frame) (X: mpred) (m0: mst) (P Q: mst -> Prop) (R: ret_assert),
  cases_nh -> stepf2_mwf3_stmt -> stepf2_hd_stmt -> stepf2_hdr_stmt -> frame_ok5 F ->
  (forall m, P m -> hdr_mode (m_mode m) = false) -> p_kept F P Q ->
  mwf3 m0 -> m_leave m0 = 0 -> hd_ok F m0 -> P m0 -> ret_ok5_hl F X m0 Q R ->
  semax Delta_inflate5_hl (lstate_hl F X m0) inflate_mainloop (overridePost (loop_exit_hl F X m0 P) R).

(* ---------------------------------------------------------------------------------------------- *)
(* the contexts                                                                                   *)

(* the headless inflate_fast specification subsumes Spec5's (frame: Loop.head_part), so Delta_cases5 and
   Delta_inflate5 are sub-contexts of the headless body's Delta_inflate5_hl; RTH8Spec's context with the headless
   specification is the port's Gprog_inflate3_hl *)
Definition rth8_delta_stmt : Prop :=
  funspec_sub (snd inflate_fast_spec3_hl) (snd inflate_fast_spec3) /\
  tycontext_sub Delta_cases5 Delta_inflate5_hl /\
  tycontext_sub Delta_inflate5 Delta_inflate5_hl /\
  Gprog_inflate8 (snd inflate_fast_spec3_hl) = Gprog_inflate3_hl.
