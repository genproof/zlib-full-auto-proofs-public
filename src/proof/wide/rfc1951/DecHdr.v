(* what the header modes must also know (DecodeDefs' at_head / at_gzhdr do not state it): total = 0
   before the data, and a raw stream is at HEAD with no bits; proved below (dh_fix) *)
Definition dh_fix_stmt_wide : Prop :=
  forall G pos inp ob m, dh_ctx_wide G pos inp ob m -> md_hdr (m_mode m) ->
    i_total (m_s m) = 0 /\ (m_mode m = HEAD -> wrapped G = false -> m_bits m < 8).

Lemma dh_group_wide (K: dkit_stmt_wide) : dh_fix_stmt_wide -> group_ok_wide md_hdr.
Proof.
  intros FX G pos inp ob flush m Hok Hp Hl Hi HK Hw Hlv Hmd.
  assert (Hc : dh_ctx_wide G pos inp ob m) by (unfold dh_ctx_wide; tauto).
  destruct (FX G pos inp ob m Hc Hmd) as (Ht & Hr).
  destruct Hmd as [M|M].
  - exact (dh_case_head_wide K G pos inp ob flush m Hc M Ht (Hr M)).
  - exact (dh_case_gz_wide K G pos inp ob flush m Hc M Ht).
Qed.

Lemma dh_fix_wide : dh_fix_stmt_wide.
Proof.
  intros G pos inp ob m (_ & _ & _ & _ & HK & _) Hmd. pose proof (kd_at _ _ _ _ _ HK) as A.
  destruct Hmd as [M|M].
  - destruct (dh_at_head _ _ _ _ _ _ A M) as (_ & (_ & _ & _ & _ & T & R & _)). split; [exact T|]. intros _. exact R.
  - destruct (dh_at_gz _ _ _ _ _ _ A M) as (_ & (h & _ & _ & _ & T & _)). split; [exact T|].
    intros E. unfold m_mode in *. dh_modes_in M. dh_modes_in E. lia.
Qed.

Lemma dec_hdr_part_wide : (dkit_stmt_wide -> decode_init_stmt_wide) /\ (dkit_stmt_wide -> group_ok_wide md_hdr).
Proof. split; intros K; [exact dh_init_wide | exact (dh_group_wide K dh_fix_wide)]. Qed.
