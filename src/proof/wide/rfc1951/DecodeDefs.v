(* inflateInit2's windowBits accepts the stream (zlib: any window from the header's to 15, 0 or 32 + the
   header's) *)
Definition accepts_wide (G: dctx) : Prop :=
  match dc_w G with
  | WRaw => dc_iw G = - dc_wb G
  | WZlib _ _ _ => dc_wb G <= dc_iw G <= 15 \/ dc_iw G = 0 \/ dc_iw G = 32 + dc_wb G
  | WGzip _ => dc_iw G = 16 + dc_wb G \/ dc_iw G = 32 + dc_wb G
  end.

Definition dctx_ok_wide (G: dctx) : Prop :=
  stream_ok (dc_w G) (dc_wb G) (dc_hist G) (dc_bs G) /\ accepts_wide G /\
  (forall h, dc_w G = WGzip h -> gz_simple h) /\
  (forall wb fl did, dc_w G = WZlib wb fl did ->
     did = None \/ did = Some (Zlib.proof.adler32.Model.ref_adler32 1 (dc_hist G))) /\
  slen G <= Zlength (dc_src G) /\ Zlength (dc_src G) <= 2 ^ 64 - 1 /\ bytes_ok (dc_src G) /\
  sublist 0 (slen G) (dc_src G) = stream_bytes (dc_w G) (dc_hist G) (dc_bs G).

Definition group_ok_wide (P_wide: Z -> Prop) : Prop :=
