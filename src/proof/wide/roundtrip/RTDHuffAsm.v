Lemma step_FP_w a : FP_w a ->
  (exists r, huff_body flush a = Some (inr r) /\ FQ_w r) \/
  (exists a', huff_body flush a = Some (inl a') /\ FP_w a').
Proof.
  destruct a as [s z]. intros [[evs HI] HK]. cbn [fst snd] in HI, HK.
  rewrite huff_body_eq. unfold hrefill.
  destruct (Z.eqb_spec (d_lookahead s) 0) as [Hl0|Hl0].
  - destruct (Href s0 z0 flush s z evs HI Hfn0 Hl0) as (s2 & z2 & E & HI2 & Hsum & Hz2).
    rewrite E. cbn [bind].
    destruct (HFI_facts_w s z evs HI) as (HW & He & Ho & Hq & Hfn & Hzz & Ha & Hw).
    destruct HK as (k & x & BS' & syms & Hz & Ht & Hk & Hb).
    destruct (Hfrefill s z s2 z2 syms dict (Dk_w k) (BS ++ BS') HW Hfn Hzz Ha Ht Hk E)
      as (k' & Hzs & Ht2 & Hk2 & Eb2 & Ep2).
    rewrite Hw in Hzs.
    assert (Hz0 : zall_w z0) by (destruct HI as (Z & _); exact Z).
    assert (Ha0 : adler_ok (d_wrap s0) (z_adler z0)) by (destruct HI as (_ & A & _); exact A).
    assert (Hzt := zstep_trans_w _ _ _ _ _ _ _ _ (proj1 Hz0) Ha0 Hz Hzs). rewrite app_nil_r in Hzt.
    assert (Hkk : 0 <= k + k' <= z_avail_in z0) by (destruct Hzt as (_ & B & _); exact B).
    rewrite (Dk_ext_w k x z k' z2 (proj1 Hz0) Hz Hzs Hkk) in Hk2.
    assert (HK2 : FK_w s2 z2).
    { exists (k + k'), x, BS', syms. split; [exact Hzt|]. split; [exact Ht2|]. split; [exact Hk2|].
      rewrite Eb2. exact Hb. }
    destruct (Z.eqb_spec (d_lookahead s2) 0) as [Hl2|Hl2].
    + left. destruct (Z.eqb_spec flush Z_NO_FLUSH) as [Hnf|Hnf].
      * eexists. split; [reflexivity|]. cbn [FQ_w]. exact (FK_FR_w s2 z2 evs need_more HI2 HK2 eq_refl).
      * eexists. split; [reflexivity|]. cbn [FQ_w]. split; [exists evs; exact HI2|].
        split; [exact HK2|]. split; [exact Hl2|]. split; [exact (Hz2 Hl2)|exact Hnf].
    + cbn [bind].
      destruct (lit_FP_w s2 z2 evs HI2 HK2 ltac:(destruct (HFI_facts_w s2 z2 evs HI2) as (HW2 & _);
                                               pose proof (W_la_bound s2 HW2); lia)) as (r & Er & Hr).
      rewrite Er. destruct r as [a'|e].
      * right. exists a'. split; [reflexivity|exact Hr].
      * left. exists e. split; [reflexivity|exact Hr].
  - cbn [bind].
    destruct (lit_FP_w s z evs HI HK ltac:(destruct (HFI_facts_w s z evs HI) as (HW & _);
                                         pose proof (W_la_bound s HW); lia)) as (r & Er & Hr).
    rewrite Er. destruct r as [a'|e].
    + right. exists a'. split; [reflexivity|exact Hr].
    + left. exists e. split; [reflexivity|exact Hr].
Qed.

Lemma loop2_FP_w : forall d a x, FP_w a -> loop2 d (huff_body flush) a = Some x ->
  match x with inl a' => FP_w a' | inr r => FQ_w r end.
Proof.
  induction d as [|d IH]; intros a x Ha E; cbn [loop2] in E.
  - destruct (step_FP_w a Ha) as [(r & Er & Hr)|(a' & Er & Ha')]; rewrite Er in E; injection E as <-; assumption.
  - destruct (loop2 d (huff_body flush) a) as [[a1|r1]|] eqn:E1.
    + exact (IH a1 x (IH a (inl a1) Ha E1) E).
    + injection E as <-. exact (IH a _ Ha E1).
    + discriminate E.
Qed.

Lemma loop_FQ_w d a r : FP_w a -> loop d (huff_body flush) a = Some r -> FQ_w r.
Proof.
  intros Ha E. unfold loop in E.
