  destruct HW3 as [[HW _] He].
  assert (Hz := zin_ok_zall_w z Hzi). assert (Ha := adler_pre_ok _ _ Had).
  assert (Hbv0 : 0 <= d_bi_valid s) by (destruct Ho as (_ & (B & _) & _); unfold d_bi_valid; lia).
