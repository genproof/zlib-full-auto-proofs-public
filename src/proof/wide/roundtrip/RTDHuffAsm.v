  { unfold HFI_w. split; [exact Hz|]. split; [exact Ha|]. split; [exact (hcrel_refl_w s z flush HW He Ho Hz Ha)|].
    split; [exact Hq|]. split; [exact Hz|]. split; [exact Ha|constructor]. }
  assert (HP0 : FP_w s z flush dict D BS p (s, z)).
  { split; [exists []; exact HI|]. cbn [fst snd].
    destruct (proj1 (kcore_hk3 _ _ _ _ _ HW Hfn) HK) as [Ht Hk].
    exists 0, [], [], syms. split; [exact (zstep_refl_w _ _ Hz Ha)|]. split; [exact Ht|].
