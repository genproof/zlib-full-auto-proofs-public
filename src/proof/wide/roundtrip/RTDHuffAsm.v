(* the functional facts at a loop state *)
Definition FK_w (s : dstate) (z : strm) : Prop :=
  exists k x BS' syms,
    zstep (d_wrap s0) z0 z k x /\ wtrees s syms /\ hk3 dict (Dk_w k) (BS ++ BS') syms s /\
    F.bytes_bits x ++ bibits s = bibits s0 ++ enc_from p BS' false.

(* the facts of the result of the call *)
Definition FR_w (s : dstate) (z : strm) (bs : bstate) : Prop :=
  exists k x BS' syms,
    zstep (d_wrap s0) z0 z k x /\ kcore dict (Dk_w k) (BS ++ BS') syms s /\
    F.bytes_bits (x ++ pend s) ++ bibits s = bibits s0 ++ enc_out p BS' (fin_bs bs) /\
    (fin_bs bs = true -> BS' <> []).

Definition FP_w (a : dstate * strm) : Prop := (exists evs, HFI_w s0 z0 flush (fst a) (snd a) evs) /\ FK_w (fst a) (snd a).
Definition FQ_w (r : dexit) : Prop :=
  let '(s', z', o) := r in
  match o with
  | Some bs => FR_w s' z' bs
  | None => (exists evs, HFI_w s0 z0 flush s' z' evs) /\ FK_w s' z' /\
            d_lookahead s' = 0 /\ z_avail_in z' = 0 /\ flush <> Z_NO_FLUSH
  end.

