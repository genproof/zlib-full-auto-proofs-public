  HFI_w s0 z0 flush s z evs -> FK_w s z -> d_lookahead s = 0 -> z_avail_in z = 0 -> flush <> Z_NO_FLUSH ->
  c_deflate_tail (set_d_insert s 0) z flush = Some (s', z', bs) -> FR_w s' z' bs.
