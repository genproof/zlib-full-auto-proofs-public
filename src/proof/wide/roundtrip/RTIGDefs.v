  (dkit_stmt_wide -> tabdec_stmt -> group_ok_wide md_type) /\
  (dkit_stmt_wide -> tabdec_stmt -> stepf2_kd_stmt -> group_ok_wide md_dec -> group_ok_wide md_tab) /\
  (dkit_stmt_wide -> dfast_stmt_wide -> group_ok_wide md_dec) /\
