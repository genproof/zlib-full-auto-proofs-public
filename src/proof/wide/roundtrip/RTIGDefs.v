  (dkit_stmt_wide -> group_ok_wide md_trl) /\
  (dkit_stmt_wide -> stepf2_kd_stmt -> group_ok_wide md_type -> group_ok_wide md_tab -> group_ok_wide md_dec -> group_ok_wide md_trl ->
     rtig_loop_stmt_wide).

Lemma rtig_of_parts_wide : rtig_parts_wide -> tabdec_stmt -> stepf2_kd_stmt -> rtig_loop_stmt_wide.
Proof.
  intros (K & Ty & Ta & De & Fa & Tr & C) T S.
  pose proof (De K (Fa K)) as DE.
  exact (C K S (Ty K T) (Ta K T S DE) DE (Tr K)).
Qed.
