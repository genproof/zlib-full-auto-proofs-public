Lemma dstream_sp_eq_za lvl os strmp ghp gv :
  dstream_za lvl os strmp ghp gv = (EX sp : val, dstream_sp_za lvl os strmp ghp sp gv)%logic.
Proof.
  unfold dstream_za, dstream_sp_za. destruct os as [s|].
  - apply pred_ext.
    + Intros p. Exists (p_s p) p. entailer!.
    + Intros sp p. Exists p. entailer!.
  - apply pred_ext.
    + Intros za zf op dt. Exists nullval za zf op dt. entailer!.
    + Intros sp za zf op dt. Exists za zf op dt. entailer!.
Qed.

