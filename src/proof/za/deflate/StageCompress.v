(** Close a branch whose condition on int constants is false. *)
Ltac bad_int :=
  match goal with
  | H : Int.repr _ = _ |- _ => apply (f_equal Int.unsigned) in H; vm_compute in H; discriminate H
  | H : Int.repr ?a <> ?b |- _ => elim H; vm_compute; reflexivity
  | H : Int.one = Int.zero |- _ => discriminate H
  | H : Int.zero <> Int.zero |- _ => elim H; reflexivity
  | H : Vint _ = Vint _ |- _ => inversion H; clear H; bad_int
  end.

