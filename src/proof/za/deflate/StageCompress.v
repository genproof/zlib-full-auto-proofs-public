  intros Espec p pin pout ish R msgv gv flush s z X s1 Hc.
  unfold c_clr in Hc. inv_bind Hc. rename x into s2, Ha into Hs2.
  unfold c_clear_hash in Hs2. inv_bind Hs2. rename x into hd1, Ha into Hwr.
  inv_bind Hs2. destruct x. apply guard_inv in Ha. inversion Hs2; subst s2; clear Hs2.
  unfold wr in Hwr. destruct (in_range _ _) eqn:Hir in Hwr; [|discriminate].
  inversion Hwr; subst hd1; clear Hwr Hir.
  rewrite andb_true_iff, Z.leb_le, Z.eqb_eq in Ha. destruct Ha as [Hhs Hzl].
  rewrite Zlength_upd_Znth in Hzl.
  unfold df_locals.
  sep_apply (dfull_hm_open_za s z p pin pout ish R msgv gv). Intros.
  unfold hash_at, match_at. Intros. rewrite Hzl.
  assert (Hhsu : d_hash_size s <= Int.max_unsigned) by (open_dranges H2; rep_lia).
  cbv [S_clear].
  assert_PROP (field_compatible (tarray tushort (d_hash_size s)) nil (p_head p)) as Hfc by entailer!.
  eapply semax_seq'.
  { apply semax_loop_nocontinue.
    forward. forward. forward.
    { entailer!. rewrite sub1_unsigned by (auto; lia). lia. }
    rewrite sub1_unsigned by (auto; lia).
    match goal with |- context [upd_Znth _ _ ?v] =>
      sep_apply (head_split' (d_hash_size s) (map vi (d_head s)) v (p_head p)) end.
    all: try solve [lia | rewrite Zlength_map; auto].
    Intros.
    forward. forward.
    forward_call (Ews, p_head p, (d_hash_size s - 1) * 2, 0).
    { entailer!. simpl. rewrite sub1_unsigned by (auto; lia). reflexivity. }
    match goal with |- context [@data_at _ _ (tarray tushort 1) [?v] _] =>
      sep_apply (head_join (d_hash_size s) v (p_head p)) end.
    all: try solve [reflexivity | lia | auto].
    forward. forward.
    apply andp_left2; apply derives_refl. }
  dsimpl in Hc.
  forward.
  forward_if.
  - assert (E : d_lookahead s = 0) by (open_dranges H2; apply repr_inj_unsigned; auto; rep_lia).
    rewrite E, Z.eqb_refl in Hc. inversion Hc; subst s1; clear Hc.
    forward. forward. forward.
    change (set_d_insert (set_d_block_start (set_d_strstart (set_d_slid (set_d_head s
              (repeat 0 (Z.to_nat (d_hash_size s)))) 0) 0) 0) 0) with (clr_st s 0 0 0).
    clr_fin_za s z 0 0 0 p pin pout ish R msgv gv.
    all: try solve [reflexivity | auto | lia | unfold u32_ok, s64_ok; rep_lia].
    entailer!.
  - assert (E : d_lookahead s <> 0) by (intro E; rewrite E in *; contradiction).
    rewrite (proj2 (Z.eqb_neq _ _) E) in Hc. inversion Hc; subst s1; clear Hc.
    forward.
    rewrite (clr_st_same s).
    clr_fin_za s z (d_strstart s) (d_block_start s) (d_insert s) p pin pout ish R msgv gv.
    all: try solve [reflexivity | auto | lia | open_dranges H2; unfold u32_ok, s64_ok; auto].
    entailer!.
Qed.

