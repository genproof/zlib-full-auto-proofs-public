    @field_at DCS.CS Ews t_ds (DOT _status) (vi (d_status s)) (p_s p) *
    @field_at DCS.CS Ews t_ds (DOT _last_flush) (vi (d_last_flush s)) (p_s p) *
    dfull_rest_za s z p pin pout ish R msgv gv))%logic.
Proof.
  unfold dfull_za, dstate_at, dfull_rest_za, stat_at, match_at, out_space. rewrite strm_at_open_za. Intros.
  entailer!.
Qed.

