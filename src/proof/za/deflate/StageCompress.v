Lemma clear_ok_za : forall (Espec : OracleKind) p pin pout ish R msgv gv flush s z X s1,
  c_clr s = Some s1 ->
  @semax DCS.CS Espec (func_tycontext f_deflate DSpec.Vprog Gprog_deflate_za nil)
    (PROPx [] (LOCALx (temp _bstate (vi 1) :: df_locals p flush gv)
     (SEPx [dfull_za s z p pin pout ish R msgv gv; deflate_globals gv; X]))) S_clear
