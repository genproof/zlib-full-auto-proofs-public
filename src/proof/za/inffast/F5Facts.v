Definition f5_concl_za (m: mst) (go: bool) (m': mst) : Prop :=
  m_inp m' = m_inp m /\ m_aout m' = m_aout m /\ m_nx m <= m_nx m' <= Zlength (m_inp m) /\
  0 <= m_bits m' <= 30 /\ m_bits m' - 8 * m_nx m' <= m_bits m - 8 * m_nx m /\ lrange (m_hold m') /\
  Zlength (m_ow m) <= Zlength (m_ow m') <= m_aout m /\
  (go = true -> fast_ok_za m' /\ m_mode m' = LEN /\ Zlength (m_ow m) < Zlength (m_ow m')).

Lemma f5_concl_bad_za: forall m mb x, mwf_za mb -> f5_same m mb ->
  m_nx m <= m_nx mb <= Zlength (m_inp m) -> 0 <= m_bits mb <= 30 ->
  m_bits mb - 8 * m_nx mb <= m_bits m - 8 * m_nx m -> mwf_za m ->
  f5_concl_za m false (set_bad mb x).
Proof.
  intros m mb x W (S1 & S2 & S3 & S4) N B G W0. pose proof (mw_hold_za _ W). pose proof (mw_ow_za _ W0).
  unfold f5_concl_za; simpl. rewrite S2, S3, S4. unfold lrange in *. repeat split; try lia; try (intros D; discriminate).
Qed.

