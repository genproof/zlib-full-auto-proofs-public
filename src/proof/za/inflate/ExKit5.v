Lemma mwf3_exlen_fin_za: forall m1, mwf_za m1 -> m_mode m1 = EXLEN -> m_hold m1 < 2 ^ 24 ->
  mwf3_za (set_mode (exlen_fin m1) EXTRA) /\ m_leave (set_mode (exlen_fin m1) EXTRA) = m_leave m1.
Proof.
  intros m1 W HM HB. unfold exlen_fin. cbv zeta.
  change (i_head (m_s (upd_s m1 (fun s => set_i_length s (u32 (m_hold m1)))))) with (i_head (m_s m1)).
  rewrite crc_if_eq.
  pose proof (u32_range (m_hold m1)) as U.
  assert (O: m_out m1 = m_aout m1).
  { apply mwf_out_eq_za; [exact W | ..]; rewrite HM; unfold EXLEN, LENGTH, DONE, BAD; lia. }
  assert (C: forall s, swf s -> lrange (crc_val s (hbytes2 (m_hold m1))))
    by (intros; apply crc_val_range; auto; apply hbytes2_ok).
  destruct W as [MD S H I A NX OW HO B IN OUT R L AD TI TO SNX SOW OE].
  destruct (i_head (m_s m1)); (split; [split | reflexivity]);
    [ | split; [apply swf3_hdr; right; left; reflexivity | unfold Zlib.proof.inflate.InvW.hdrW; cbn -[crc_val]; split; intros X; [exfalso; unfold EXLEN, EXTRA in X; lia | intros _; unfold u32; rewrite Z.mod_small by (unfold lrange in HO; lia); rep_lia]]
      | | split; [apply swf3_hdr; right; left; reflexivity | unfold Zlib.proof.inflate.InvW.hdrW; cbn -[crc_val]; split; intros X; [exfalso; unfold EXLEN, EXTRA in X; lia | intros _; unfold u32; rewrite Z.mod_small by (unfold lrange in HO; lia); rep_lia]]];
    (constructor; cbn -[crc_val Int.max_unsigned]; auto;
     [ apply modewf_hdr; right; left; reflexivity
     | destruct S; constructor; cbn -[crc_val Int.max_unsigned]; auto;
       [ unfold EXTRA, HEAD, SYNC; lia | apply C; constructor; auto ]
     | ..]).
  - destruct H; constructor; cbn; auto.
  - unfold initbits, lrange; cbn; rep_lia.
  - unfold initbits; cbn; lia.
  - unfold initbits, lrange; cbn; rep_lia.
  - unfold initbits; cbn; lia.
Qed.

