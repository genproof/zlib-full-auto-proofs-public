  - unfold lrange, u64. pose proof (Z.mod_pos_bound (m_hold m + Znth (m_nx m) (m_inp m) * 2 ^ m_bits m) (2^64)). rep_lia.
  - unfold u32. rewrite Z.mod_small by lia. lia.
Qed.

