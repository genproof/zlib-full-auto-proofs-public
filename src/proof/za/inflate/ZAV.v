(* The member strm->adler of a z_stream that inflate.c works on, as the allocator-generic port of inflate's
   proofs (src/proof/za/inflate*, generated by docs/port-za/port.py with docs/port-za/cfg_inflate.py)
   represents it.

   On a zlib or gzip stream the member holds the check value of the model (a Z, written by inflate() and
   inflateResetKeep).  On a raw stream (windowBits -8..-15) zlib never sets it: inflateResetKeep writes it
   only when state->wrap <> 0, an application that does not set it (laws_common.h's new_stream) leaves it
   undefined, and inflate() and inflateSetDictionary never read it.  The port's representations take the
   member as [adler_val adler]: with [av_undef = false] the model's value, with [av_undef = true] Vundef,
   which in a data_at means any contents (a store into it keeps it so: case DICT of inflate() on a raw
   stream writes it).  The class is a section parameter of the generated files, beside the allocator. *)
Require Import VST.floyd.proofauto.

Class adler_cell := AdlerCell { av_undef : bool }.

Definition adler_val {AV : adler_cell} (adler : Z) : val :=
  if av_undef then Vundef else Vlong (Int64.repr adler).

(* the two instances *)
Definition av_defined : adler_cell := AdlerCell false.
Definition av_any : adler_cell := AdlerCell true.

Lemma adler_val_defined: forall a, @adler_val av_defined a = Vlong (Int64.repr a).
Proof. reflexivity. Qed.

Lemma adler_val_any: forall a, @adler_val av_any a = Vundef.
Proof. reflexivity. Qed.
