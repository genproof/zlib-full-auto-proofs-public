(* the memory after a reset: on Z_OK the live stream (for RRaw: with the fields the reset wrote,
   raw_after_init), otherwise the stream unchanged *)
Definition reset_post_za (gv: globals) (shs: share) (strmp: val) (z: zfields) (r: rst)
    (f: zfields -> live -> Z * zfields * live) : mpred :=
  match rs_live strmp r with
  | Some L => if fst3 (f z L) =? Z_OK then
                match r with
                | RRaw _ rf _ _ _ _ => istream_raw_za gv shs strmp (raw_after_init rf (l_s (thd3 (f z L)))) (thd3 (f z L))
                | _ => istream_za gv shs strmp (snd3 (f z L)) (Some (thd3 (f z L)))
                end
              else rstream_opt_za gv shs strmp z r
  | None => rstream_opt_za gv shs strmp z r
  end.

