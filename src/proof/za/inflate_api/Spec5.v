Definition rstream_za (gv: globals) (shs: share) (strmp: val) (z: zfields) (r: rst) : mpred :=
  match r with
  | RNone => istream_za gv shs strmp z None
  | RLive L vl vd vn vs =>
      !! (zf_ok z /\ writable_share shs /\ isptr (l_sp L) /\ HEAD <= i_mode (l_s L) <= SYNC /\
          0 <= i_wbits (l_s L) <= 23) &&
      (zstrm_at_za gv shs strmp z (l_sp L) * za_tok t_state (l_sp L) *
       state_rep_v gv (l_sp L) strmp (l_headp L) (l_winp L) (l_s L) vl vd vn vs *
       win_rep_za (l_winp L) (l_s L) * state_pad (l_sp L))
  | RRaw L r vl vd vn vs =>
      !! (writable_share shs /\ isptr (l_sp L) /\ HEAD <= i_mode (l_s L) <= SYNC /\
          0 <= i_wbits (l_s L) <= 23) &&
      (raw_strm gv shs strmp r nullval (l_sp L) za_alloc za_free za_opaque *
       za_tok t_state (l_sp L) *
       state_rep_v gv (l_sp L) strmp (l_headp L) (l_winp L) (l_s L) vl vd vn vs *
       win_rep_za (l_winp L) (l_s L) * state_pad (l_sp L))
  end.

