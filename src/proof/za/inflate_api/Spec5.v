(* a live stream whose application fields are values (rawf): an istream once they are defined *)
Definition istream_raw_za (gv: globals) (shs: share) (strmp: val) (r: rawf) (L: live) : mpred :=
  !! (writable_share shs /\ live_ok L) &&
  (raw_strm gv shs strmp r nullval (l_sp L) za_alloc za_free za_opaque * state_mem_za gv strmp L).

Lemma istream_raw_istream_za: forall gv shs strmp z L,
  zf_ok z -> zf_msg z = None ->
  istream_raw_za gv shs strmp
    (RF (zf_ni z) (Vint (Int.repr (zf_ai z))) (Vlong (Int64.repr (zf_tin z))) (zf_no z)
        (Vint (Int.repr (zf_ao z))) (Vlong (Int64.repr (zf_tout z))) (Vint (Int.repr (zf_dt z)))
        (adler_val (zf_adler z)) (zf_res z)) L
  = istream_za gv shs strmp z (Some L).
Proof.
  intros gv shs strmp z L Hz Hm. unfold istream_raw_za, istream_za, zstrm_at_za, strm_rep_za, raw_strm. rewrite Hm.
  simpl msg_val. apply pred_ext; entailer!.
Qed.

Definition init_mem_za (gv: globals) (shs: share) (strmp: val) (r: rawf) (msgv stv opq: val) (ret: Z)
    (sp: val) (w: Z) : mpred :=
  if eq_dec strmp nullval then emp else
  if ret =? Z_VERSION_ERROR then raw_strm gv shs strmp r msgv stv za_alloc za_free za_opaque
  else if ret =? Z_MEM_ERROR then raw_strm gv shs strmp r nullval stv za_alloc za_free za_opaque
  else if ret =? Z_OK then
    let L := init_live sp w in istream_raw_za gv shs strmp (raw_after_init r (l_s L)) L
  else raw_strm gv shs strmp r nullval nullval za_alloc za_free za_opaque.

