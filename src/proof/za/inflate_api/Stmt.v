(* What the allocator-generic port of inflate.c's proofs proves (src/proof/za/inflate*, generated by
   docs/port-za/port.py with docs/port-za/cfg_inflate.py; the specifications in the generated
   src/proof/za/inflate_api/Spec5.v and src/proof/za/inflate/Callees3.v):

   for every caller-supplied allocator ZA (src/proof/zutil/ZAlloc.v) and adler cell ZAV
   (src/proof/za/inflate/ZAV.v), the bodies of the functions of inflate.c that inflate() reaches (inflate,
   inflate_fast, updatewindow, inflateStateCheck), of inflateSetDictionary, of inflateInit2_ and the reset
   functions it calls, and of inflateEnd, each against its allocator-generic specification with the context
   of its callees.

   inflate()'s body comes, as in the default-allocator proof (src/proof/inflate_api/LibProof5.v), from the
   case lemmas of the switch (cases_all5_za), the preservation of the wide machine invariant by one pass of
   the switch (stepf2_mwf3_stmt_za: mwf3_za is InvW.mwf3W, so it follows from InvW.stepf2_mwf3W_stmt) and of
   the header pointer facts (Bodies5.stepf2_hd_stmt, proved by LibProof5.stepf2_hd_proof). *)
Require Import VST.floyd.proofauto.
Require Import VST.floyd.library.
Require Zlib.units.Inflate.
Require Import Zlib.inflate.code.
Require Export Zlib.proof.za.inflate_api.Bodies5.
Require Import Zlib.proof.inffast.Body.
Require Zlib.proof.inflate.InvW.
Require Import Zlib.proof.zutil.ZAlloc.
Require Import Zlib.proof.za.inflate.ZAV.
#[local] Existing Instance Zlib.units.Inflate.CS.

(* updatewindow's callees: zmemcpy (ZALLOC calls through strm->zalloc) *)
Definition Gp_updatewindow_za : funspecs :=
  [(_memcpy, snd (@Zlib.proof.zutil.Libc.memcpy_spec Zlib.units.Inflate.CS))].

Section Bodies.
Context {ZA : zallocator} {ZAV : adler_cell}.

(* the switch cases *)
Definition za_cases : Prop := cases_all5_za.

(* inflate_fast *)
Definition za_fast : Prop :=
  forall (Espec : OracleKind),
    semax_body Vprog_fast Gprog_fast Zlib.inffast.code.f_inflate_fast inflate_fast_spec3_za.

(* the other bodies: updatewindow, inflateStateCheck, inflateSetDictionary, inflateInit2_, inflateResetKeep,
   inflateReset, inflateReset2, inflateEnd *)
Definition za_api : Prop :=
  forall (Espec : OracleKind),
    semax_body Vprog_inflate Gp_updatewindow_za f_updatewindow updatewindow_spec3_za /\
    semax_body Vprog_inflate [] f_inflateStateCheck inflateStateCheck_spec_za /\
    semax_body Vprog_inflate Gp_setdict_za f_inflateSetDictionary inflateSetDictionary_spec_za /\
    semax_body Vprog_inflate Gp_init2_za f_inflateInit2_ inflateInit2__spec_za /\
    semax_body Vprog_inflate Gp_resetkeep_za f_inflateResetKeep inflateResetKeep_spec_za /\
    semax_body Vprog_inflate Gp_reset_za f_inflateReset inflateReset_spec_za /\
    semax_body Vprog_inflate Gp_reset2_za f_inflateReset2 inflateReset2_spec_za /\
    semax_body Vprog_inflate Gp_end_za f_inflateEnd inflateEnd_spec_za.

End Bodies.

(* the switch cases, for every allocator and adler cell *)
Definition za_cases_stmt : Prop := forall (ZA : zallocator) (ZAV : adler_cell), @za_cases ZA ZAV.

(* inflate()'s body from the cases and the two invariants *)
Definition za_body_inflate_stmt : Prop :=
  forall (ZA : zallocator) (ZAV : adler_cell), @body_inflate_from_cases5_za ZA ZAV.

(* the machine invariant of the port is InvW's: its preservation follows from InvW.stepf2_mwf3W_stmt *)
Definition za_step_stmt : Prop :=
  Zlib.proof.inflate.InvW.stepf2_mwf3W_stmt -> stepf2_mwf3_stmt_za.

Definition za_fast_stmt : Prop := forall (ZA : zallocator) (ZAV : adler_cell), @za_fast ZA ZAV.

Definition za_api_stmt : Prop := forall (ZA : zallocator) (ZAV : adler_cell), @za_api ZA ZAV.
